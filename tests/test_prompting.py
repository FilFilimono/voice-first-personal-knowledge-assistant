"""Набор раскачки: сам список вопросов и правила, которым он обязан отвечать.

Быстрый файл — без базы и без сети. Здесь проверяется то, что можно проверить
над текстом: форма вопроса, число вопросительных знаков, прохождение гварда.
Путь от `service.tick` до сообщения владельцу — в `test_prompting_path.py`,
и это разделение не косметическое: тест на функцию не заменяет теста на путь
(`CLAUDE.md`), поэтому файл про тексты не имеет права быть единственным.

**Почему гвард гоняется по всему набору, а не по паре примеров.** Разбор
источников (`docs/prompting_sources.md`, §4.1) называет механизм: владелец,
получивший упрёк, перестаёт отвечать честно, а система, вся ценность которой
в архиве, тем самым разрушает собственное сырьё. Значит, упрёк в наборе
недопустим не в одном вопросе, а ни в одном, — и проверяться это обязано
списком целиком, иначе десятый добавленный вопрос проедет мимо.

**Образцы подстановки выдуманы намеренно, и это единственное место, где так.**
Живая речь в git не уходит (ADR-0002), а проверить здесь надо шаблон —
те слова вопроса, которые пишем мы. Цитаты из живого архива подставляются
в `test_prompting_path.py`, где архив берётся из базы по номеру записи.
"""

from brain.core.digest import prompting
from brain.core.present import guard


def _rendered() -> list[tuple[str, str]]:
    """Весь набор, собранный на образцах: ключ вопроса и готовый текст."""
    return [(kind, prompting.sample(kind)) for kind in prompting.SET]


def test_the_set_is_not_empty_and_every_question_names_its_method() -> None:
    """Вопрос без опоры на источник в набор не идёт (`vision.md` §5.9).

    Опора хранится строкой рядом с вопросом, а не в шапке модуля: шапку
    при добавлении десятого вопроса не читают, а соседнее поле видно.
    """
    assert prompting.SET

    for kind, item in prompting.SET.items():
        assert item.method.strip(), f"у вопроса {kind} не назван приём разбора"
        assert item.source.strip(), f"у вопроса {kind} не названа опора в источниках"


def test_every_question_of_the_set_passes_the_guard() -> None:
    """Гвард не ослабляем, и раскачка идёт через него наравне со всем прочим."""
    for kind, text in _rendered():
        assert guard.reproach(text) is None, f"вопрос {kind} читается упрёком: {text!r}"


def test_every_question_asks_exactly_once() -> None:
    """Один вопрос в сообщении — источники единогласны (разбор, §1.3).

    Считается знаками вопроса, а не намерением: «что сделал? почему не вышло?»
    — это ловушка допроса, и отличается она от разрешённого ровно вторым «?».
    """
    for kind, text in _rendered():
        assert text.count("?") == 1, f"вопрос {kind} спрашивает не один раз: {text!r}"


def test_no_question_of_the_set_scores_the_owner() -> None:
    """Ни стриков, ни счётчиков, ни процентов (`vision.md` §7.0, п.5).

    Проверяется по словам счёта, а не по цифрам: «за три дня ни одной записи»
    — разрешённая владельцем формулировка, и цифра в ней есть. Запрещено
    другое — считать вслух сделанное и несделанное.
    """
    forbidden = ("подряд дней", "%", "из них", "всего за", "серия", "стрик")
    for kind, text in _rendered():
        lowered = text.lower()
        for word in forbidden:
            assert word not in lowered, f"вопрос {kind} считает вслух: {word!r}"


def test_a_message_that_already_asks_gets_no_second_question() -> None:
    """То же правило «один вопрос», но на уровне сообщения целиком.

    Утренняя сводка кончается вопросом петли, когда петля есть. Приписать
    к ней раскачку значит задать два вопроса подряд — то самое, чего источники
    не рекомендуют единогласно.
    """
    assert prompting.fits("☀️ Утро.\n\nВисит:\n1. купить хлеб") is True
    assert prompting.fits("🔁 Ты хотел разобраться: куда дальше\nСдвинулось?") is False


def test_the_question_is_shown_apart_from_the_rest() -> None:
    """Раскачка отбита от сводки пустой строкой и своим значком.

    Иначе вопрос читается как продолжение списка дел, а не как обращение.
    """
    joined = prompting.attach("☀️ Утро.\n\nВисит:\n1. купить хлеб", "Что вчера помешало?")
    assert joined.endswith("Что вчера помешало?")
    assert "\n\n" in joined
    assert joined.splitlines()[-1] != "1. купить хлеб"
