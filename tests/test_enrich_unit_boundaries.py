"""Граница смысловой единицы обязана нести предмет своего действия.

Долг закрыт 27.08.2026 правкой `UNIT_RULES`. Здесь два разных утверждения,
и разносить их нельзя:

- **инструкция** говорит модели то, что решил владелец, — проверяется текстом
  промпта. Обычно проверять промпт строкой не стоит, но здесь строка и есть
  предмет правки: поведение модели проверяется замером, а не быстрым тестом,
  а вот «правило вообще сказано» обязано держаться тестом. Ровно этот тест
  и поймал бы долг «промпт единиц отстал от определения», проживший неделю;
- **прибор**, которым цена правки меряется по базе, — проверяется на живой
  речи, по номеру записи, а не на выдуманной фразе.
"""

import pytest

from brain.core.enrich import prompt
from evals.units import checks
from tests import archive as archive_module

# Запись 15 целиком: «по итогу я перенес Cv чек на завтра в 16:00 , сейчас надо
# к нему полностью подготовится». Ею ADR-0012 обосновывал границу внутри
# предложения — и ровно она дала одно из девяти неназываемых дел.
SPLIT_AT = "сейчас надо"


def test_prompt_says_unit_is_one_deed() -> None:
    """Долг «промпт единиц отстал от определения» (ADR-0012, «Обновление»)."""
    system = prompt.build_system([])

    assert "одно дело" in system
    # Формулировка старого определения. Она противоречила замыслу и держалась
    # только тем, что модель ей не следовала.
    assert "у каждого свой тип" not in system


def test_prompt_forbids_cutting_pronoun_from_its_owner() -> None:
    """Девять неназываемых отрезков из одиннадцати — ровно этот случай."""
    system = prompt.build_system([])

    assert "предмет своего действия" in system
    assert "местоимением" in system


def test_pronoun_without_owner_is_visible_on_live_speech(
    archive: list[archive_module.Entry],
) -> None:
    """Целая запись самодостаточна, отрезанная половина — нет.

    Это и есть дефект в одном утверждении: слов не убавилось, а назвать вторую
    половину стало нечем. Текст берётся из базы по номеру записи, а не из головы
    (`tests/archive.py`).
    """
    entry = archive_module.entry(archive, 15)
    if SPLIT_AT not in entry.text:
        pytest.skip(f"запись 15 в архиве другая: {entry.text[:60]!r}")

    head, tail = entry.text.split(SPLIT_AT, maxsplit=1)

    assert checks.dangling(entry.text) == []
    assert checks.dangling(SPLIT_AT + tail) == ["нему"]
    # Первая половина без второй проверяется тоже: прибор обязан молчать там,
    # где дефекта нет, иначе его число ничего не значит.
    assert checks.dangling(head) == []


def test_owner_named_inside_the_unit_is_not_a_defect() -> None:
    """«Перенёс CV-чек, надо к нему подготовиться» одной единицей — норма.

    Правка промпта именно к этому и ведёт: не «убрать местоимения», а «оставить
    их вместе с хозяином». Прибор, считающий такую единицу дефектной, показывал
    бы, что правка не работает, ровно тогда, когда она работает.
    """
    assert checks.dangling("перенёс CV-чек на завтра, надо к нему подготовиться") == []


def test_owner_of_the_pronoun_is_looked_for_only_on_the_left() -> None:
    """Хозяин, названный после местоимения, единицу не спасает.

    «Надо её читать, книгу эту» — так не говорят, и правило «смотрим влево»
    держится на этом. Проверка нужна затем, чтобы прибор не начал молча
    засчитывать хозяина справа: тогда он перестал бы видеть половину дефектов.
    """
    assert checks.dangling("надо её каждый день начинать читать") == ["её"]
