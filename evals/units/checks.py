"""Признак «единица не несёт предмета своего действия» — кодом, без модели.

Долг найден 27.08.2026 полным прогоном названий: модель вернула пустое
название на 11 отрезках из 72, и у **девяти** из одиннадцати действие есть,
а предмет — местоимение без хозяина. «В общем, надо **её** каждый день
начинать читать», «надо **к нему** полностью подготовится». Книга и экзамен
названы абзацем раньше и остались в соседней единице.

**Зачем код, если дефект уже посчитан моделью.** Базовая линия (11 из 72)
снята прогоном названий, то есть 72 вызовами дорогой модели под суточным
лимитом в двадцать. Повторять её после каждой правки промпта нечем: это
четыре дня прогонов. Признак ниже считает то же место **по данным**, за один
запрос к базе и ноль вызовов провайдера, — и потому его можно считать
до перепрогона, после перепрогона и на любой редакции промпта.

**Это прибор, а не проверка правоты.** Он ловит ровно одно: местоимение,
у которого внутри своей единицы нет ничего, к чему оно могло бы относиться.
Из одиннадцати неназываемых отрезков он видит девять — остальные два («действия
нет вовсе», «действие слишком общее») не про границу и здесь не считаются.
Числа поэтому сравниваются с числами того же прибора, а не с одиннадцатью.

**Морфологии здесь нет и не будет.** Разбирать род и число честно умеет только
библиотека, а это новая зависимость и отдельный ADR (та же причина, по которой
`reminders.IMPERATIVE_VERBS` — список, а не правило). Взамен взята проверка,
которой морфология не нужна вовсе: у местоимения ищется **хоть какое-нибудь
знаменательное слово слева от него внутри той же единицы**. Хозяин местоимения
стоит слева — на этом весь дефект и держится; если слева нет ничего, кроме
служебных слов, то и хозяина в единице нет.
"""

