WORD = re.compile(r"[а-яёa-z0-9]+(?:-[а-яёa-z0-9]+)*", re.IGNORECASE)


def dangling(text: str) -> list[str]:
    """Местоимения этой единицы, у которых внутри неё нет хозяина.

    Пусто — единица самодостаточна: либо местоимений нет вовсе, либо слева
    от каждого стоит слово, которым его можно понять.

    Смотрим **влево** и только влево. Хозяин местоимения по-русски почти
    всегда назван раньше него, и весь дефект в том, что «раньше» осталось
    в соседней единице.
    """
    words = [(match.group(0).lower(), match.start()) for match in WORD.finditer(text)]
    found: list[str] = []
    for index, (word, _) in enumerate(words):
        if word not in ANAPHORIC:
            continue
        if any(earlier not in FUNCTION_WORDS for earlier, _ in words[:index]):
            continue
        found.append(word)
    return found


def is_dangling(text: str) -> bool:
    """Единица, которую нечем назвать: местоимение есть, хозяина нет."""
    return bool(dangling(text))
