"""Что можно проверить кодом, сравнив дословный текст с вычищенным.

Граница чистки записана в ADR-0015 и в промпте первой строкой: убрать
слова-паразиты, самоповторы, оборванные начала, расставить знаки и заглавные —
и **не трогать** смысл, лексику, отрицания, числа, имена и даты. Отсюда
и проверки: каждая из них — это одна строка той границы, переведённая
в регулярное выражение.

**Чего эти проверки не ловят — сказано вслух, потому что зелёный прогон иначе
прочтётся как «чистка не теряет смысл».** Выкинутое придаточное («потому что
он всё равно уезжает») не содержит ни цифр, ни имён, ни «не» — по всем
проверкам ниже оно пройдёт чисто. Потерю такого рода видит только владелец,
и ради неё в замере есть второй уровень — размеченный набор.

**Порог длины — не отказ.** Чистка законно сокращает: «э ну надо это самое
надо мне посмотреть» превращается в «Надо посмотреть», и это ровно то, ради
чего она заведена. Поэтому `LENGTH_FLOOR` не входит в `ok`, а даёт отдельный
признак `too_short`: повод открыть запись глазами, а не нарушение.
"""

import re
from dataclasses import dataclass

# Падение длины больше чем вдвое. Не нарушение (см. шапку), а повод посмотреть
# руками: настоящая потеря куска текста выглядит именно так.
LENGTH_FLOOR = 0.5

# Число, время и дата — одним куском: «19:40» показывается в замечании целиком,
# иначе список замечаний состоит из цифр без смысла.
NUMBER = r"\d+(?:[:.,]\d+)*"

# Слово — либо число целиком, либо буквы (с дефисом и апострофом внутри:
# «по-моему» и «don't» — по одному слову). Порядок веток важен: число должно
# отбираться раньше, чем буквенная ветка доберётся до его частей.
WORD = re.compile(rf"{NUMBER}|[^\W\d_]+(?:[-'][^\W\d_]+)*", re.UNICODE)

NUMBERS = re.compile(NUMBER)

# Цифровые группы и разделители внутри слова. Сравнение идёт **по ним**,
# а не по строке слова целиком, и это не мелочь.
#
# Промпт велит чистке расставлять знаки препинания. Значит, «встреча 24 08
# в 19 40» законно превращается в «Встреча 24.08 в 19:40», а «по моему» —
# в «По-моему». Сравнение по строке объявило бы это потерей четырёх чисел
# и выдумкой двух — то есть модель, которая **аккуратнее** ставит двоеточие
# во времени, получила бы худшую оценку. Головное число прогона — доля записей
# без замечаний, по ней сравниваются модели, и такой замер награждал бы
# за небрежность.
#
# Цена названа: перестановка целых групп местами («19:40» → «40:19») пройдёт
# как «все группы на месте». Изменение любой цифры внутри группы — нет.
DIGITS = re.compile(r"\d+")
INSIDE_WORD = re.compile(r"[-']")

# Латиница в русском тексте — надёжный признак имени собственного: «Michael»,
# «Discord», «CV». Заглавной в начале предложения она не бывает по случайности,
# потому что предложения владельца начинаются с кириллицы.
LATIN = re.compile(r"[A-Za-z]")

# Отрицания считаются штучно. Потерянное «не» переворачивает запись целиком,
# и это единственная потеря слова, которую код умеет заметить: остальные слова
# чистка убирать вправе.
NEGATIONS = frozenset({"не", "ни"})

# Конец предложения. После любого из этих знаков следующее слово будет
# с заглавной у кого угодно, а не только у имени собственного.
SENTENCE_END = frozenset(".!?…\n")

# Слова, которые чистке убирать **велено промптом** (`core/present/cleanup`).
# Именем собственным ни одно из них не бывает, и держать их среди кандидатов
# нельзя ни при каком регистре.
#
# Список появился не из осторожности, а из замера: расшифровка ставит заглавную
# после паузы, в том числе в середине фразы («надо, соответственно, Ну,
# посмотреть»), и на живом архиве это дало **все** ложные срабатывания подряд —
# четыре записи из семидесяти при заведомо законной чистке.
#
# **Расширять его не надо.** Он закрывает четыре слова, попавшихся на этих
# семидесяти записях, а не явление: «соответственно», «получается», «допустим»,
# «просто» дадут ровно то же ложное срабатывание. Гнаться за полнотой — та же
# бесконечная работа, что стоп-лист повелительных глаголов в `reminders`.
# Поэтому и в README написано «ноль ложных на **текущем** архиве», а не «ноль».
FILLERS = frozenset(
    {"ну", "вот", "это", "самое", "как", "бы", "типа", "короче", "значит", "так", "да"}
)

# Что может стоять между концом предложения и первым словом следующего:
# пробелы, кавычки, скобки, тире. Прыгая через них, мы не принимаем
# «— Привет» за середину фразы.
BEFORE_WORD = frozenset(" \t\r«»\"'([{-—–")


def normalize(word: str) -> str:
    """Слово в сравнимом виде: регистр и «ё» не считаются различием.

    Расшифровка и чистка пишут «ещё» и «еще» как придётся, а разница между
    ними — это разница провайдеров, а не потеря смысла.
    """
    return word.lower().replace("ё", "е")


def parts(word: str) -> list[str]:
    """Слово, разложенное на части, к пунктуации нечувствительные.

    «19:40» → «19», «40»; «что-то» → «что», «то». Так знаки, которые чистка
    обязана расставить, перестают выглядеть потерей и выдумкой сразу.
    """
    if DIGITS.search(word):
        return DIGITS.findall(word)
    return [part for part in INSIDE_WORD.sub(" ", normalize(word)).split() if part]


def words(text: str) -> list[str]:
    """Все части текста — словарь, по которому идёт сравнение."""
    return [part for match in WORD.finditer(text) for part in parts(match.group())]


def _missing(word: str, vocabulary: set[str]) -> bool:
    """Нет ли слова в словаре — пропала (или появилась) хоть одна его часть."""
    return any(part not in vocabulary for part in parts(word))


def _unique(items: list[str]) -> list[str]:
    """Без повторов, в порядке первого появления — чтобы список читался глазами."""
    seen: set[str] = set()
    result: list[str] = []
    for item in items:
        key = normalize(item)
        if key not in seen:
            seen.add(key)
            result.append(item)
    return result


def _starts_a_sentence(text: str, start: int) -> bool:
    """Стоит ли слово в начале предложения.

    **Это и есть ответ на ловушку с именами собственными.** Признак «слово
    с заглавной» в русском тексте сам по себе не работает: расшифровка ставит
    заглавные непоследовательно, а чистка обязана их расставить — значит,
    заглавная в начале фразы появится у любого слова, включая «Ну» и «Надо»,
    которые чистка вправе убрать. Считая их именами, замер выдавал бы
    замечание почти на каждой записи.

    Поэтому именем считается заглавная **внутри** фразы: в русском языке
    в середине предложения с большой буквы пишется только имя собственное.

    Цена признана явно: имя, встретившееся в записи только первым словом
    предложения, замер пропустит. Пропущенное замечание здесь дешевле ложного —
    ложные срабатывания на каждой записи означают, что список замечаний
    перестанут читать вовсе.
    """
    index = start - 1
    while index >= 0 and text[index] in BEFORE_WORD:
        index -= 1
    return index < 0 or text[index] in SENTENCE_END


def _is_filler(word: str) -> bool:
    """Мусорное ли это слово — то, которое чистке убирать разрешено.

    Три случая: список выше, одиночная буква и растянутое междометие («э-э»,
    «мммм»). Последние два — одно и то же явление: пауза, которую расшифровка
    записала буквами и начала с заглавной.
    """
    core = re.sub(r"[-']", "", normalize(word))
    if core in FILLERS or len(core) == 1:
        return True
    return len(set(core)) == 1


def _is_proper_name(text: str, match: re.Match[str]) -> bool:
    """Имя ли это собственное. Три правила, и они разной надёжности."""
    word = match.group()

    # Латиница в русском тексте — надёжный случай: заглавной в начале
    # предложения она не бывает, потому что предложения начинаются
    # с кириллицы. Позиция здесь не важна вовсе.
    if LATIN.search(word):
        return True

    # Слово-паразит именем не бывает, в каком бы регистре его ни записали.
    if _is_filler(word):
        return False

    # Кириллица с заглавной — только внутри фразы, см. `_starts_a_sentence`.
    return word[:1].isupper() and not _starts_a_sentence(text, match.start())


def proper_names(text: str) -> list[str]:
    """Имена собственные текста — в том виде, в каком они в нём написаны."""
    return _unique([match.group() for match in WORD.finditer(text) if _is_proper_name(text, match)])


def _lost(expected: list[str], vocabulary: set[str]) -> list[str]:
    """Что из `expected` не нашлось в словаре — и в каком виде это показать.

    Сравнение по множеству, а не по числу вхождений: самоповтор («Michael
    Michael написал») чистка убирать вправе, и требовать двух вхождений
    значило бы ловить её за то, ради чего она заведена.

    Показывается слово целиком («19:40»), а сравниваются его части («19»,
    «40»): читать замечание надо глазами, а сверять — без оглядки на знаки.
    """
    return [item for item in _unique(expected) if _missing(item, vocabulary)]


@dataclass(frozen=True, slots=True)
class Report:
    """Чем вычищенный текст отличается от дословного.

    Все поля — про **потерю или выдумку**, а не про разницу вообще: разница
    и есть смысл чистки. `ok` означает «код замечаний не нашёл», а не «смысл
    сохранён» — второе кодом не проверяется (см. шапку модуля).
    """

    new_words: list[str]
    lost_numbers: list[str]
    lost_names: list[str]
    lost_negations: int
    length_ratio: float

    @property
    def ok(self) -> bool:
        """Ни одного замечания. Длина сюда не входит намеренно — она не нарушение."""
        return (
            not self.new_words
            and not self.lost_numbers
            and not self.lost_names
            and self.lost_negations == 0
        )

    @property
    def too_short(self) -> bool:
        """Текст ужался больше чем вдвое — повод открыть запись глазами."""
        return self.length_ratio < LENGTH_FLOOR

    @property
    def findings(self) -> list[str]:
        """Замечания строками — для печати прогоном. Пусто, если их нет."""
        lines = []
        if self.new_words:
            lines.append("новые слова: " + ", ".join(self.new_words))
        if self.lost_numbers:
            lines.append("потеряны числа: " + ", ".join(self.lost_numbers))
        if self.lost_names:
            lines.append("потеряны имена: " + ", ".join(self.lost_names))
        if self.lost_negations:
            lines.append(f"потеряно отрицаний: {self.lost_negations}")
        return lines


def compare(verbatim: str, clean: str) -> Report:
    """Сравнить дословный текст с вычищенным.

    Чистая функция без вызовов наружу: её гоняют быстрые тесты, а прогон
    зовёт её после каждого ответа модели.
    """
    verbatim_words = words(verbatim)
    clean_words = words(clean)
    known = set(verbatim_words)
    appeared = set(clean_words)

    negations_before = sum(word in NEGATIONS for word in verbatim_words)
    negations_after = sum(word in NEGATIONS for word in clean_words)

    return Report(
        # Новое слово — то, которого в дословном варианте не было ни разу.
        # Выдуманное число попадает сюда же: отдельного поля у него нет,
        # потому что «дописанное» и «изменённое» — это одно и то же событие,
        # видное с двух сторон (число исчезло + число появилось).
        new_words=_lost([match.group() for match in WORD.finditer(clean)], known),
        lost_numbers=_lost(NUMBERS.findall(verbatim), appeared),
        lost_names=_lost(proper_names(verbatim), appeared),
        # Потеря, а не разница: лишнее отрицание — это выдумка, и ловится оно
        # как новое слово. Считать разницу по модулю значило бы сообщать
        # об одном и том же событии двумя полями.
        lost_negations=max(0, negations_before - negations_after),
        length_ratio=len(clean) / len(verbatim) if verbatim else 1.0,
    )
