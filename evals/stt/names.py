"""Доля искажённых имён собственных — вторая метрика замера, и главная.

**Почему одного WER мало.** WER отвечает на вопрос «много ли слов услышано
неверно» и считает все слова равными. Имя в записи одно на сотню слов, поэтому
движок, перевравший все имена и не тронувший остальное, покажет WER около
процента — то есть отличный. А ломает систему дальше по цепочке именно имя.

Цена у этой поломки необратимая. Испорченное имя ложится в `transcripts.text` —
таблицу, которая не правится (инвариант 3), — и уезжает **во всё сразу**:
в разметку, в чанки, в поиск, в дела и в названия. Поиск по «GitHub» запись
с «Гидхабе» не найдёт никогда, и починить это перепрогоном нельзя: аудио живёт
тридцать дней, а строка расшифровки — всегда.

Наблюдено 27.08.2026 на одном и том же входе: Handy (локальный Parakeet)
слышит «CV чек» верно, Gemini даёт «Ксюши чеку» и «Сиви-чекку», а GitHub —
«Гидхабе». Разница между движками, а не нехватка словаря; глоссарий тут
не лечит.

**Признак имени сюда не переписан, а взят готовым** — `evals/cleanup/checks`.
Он там чинился 26.08.2026 по живому архиву, и цена его названа вслух: латиница
от трёх букв — имя, короче — только целиком заглавными («CV», «MD»); кириллица
с заглавной — только внутри фразы; слово-паразит и растянутое междометие
именем не бывают ни при каком регистре. Второй признак разошёлся бы с первым
молча, и два замера проекта начали бы считать разное под одним словом «имя».

**Что метрика считает искажением.** Имя эталона, которого нет в расшифровке
**ни в каком виде**. Сравниваются части слова, а не строка целиком: «19:40»
и «по-моему» разбираются на куски той же функцией, что и в соседнем замере,
поэтому расставленный знак препинания искажением не считается.

**Чего метрика не поймает — названо вслух**, чтобы ноль не читался как
«имена целы»:
  · имя, которое движок услышал верно, но в другой форме («Майклу» вместо
    «Майкл»), считается искажённым — падеж от подмены здесь не отличается;
  · имя, встретившееся в эталоне только первым словом предложения и записанное
    кириллицей, не будет замечено вовсе (правило `_starts_a_sentence`);
  · имя, которого владелец в эталоне не написал, метрику не интересует
    в принципе: она смотрит на эталон, а не на выдумки движка. Выдумки ловит
    WER.
"""

from dataclasses import dataclass, field

from evals.cleanup import checks


@dataclass(frozen=True, slots=True)
class Names:
    """Имена одной записи: сколько их было в эталоне и какие движок потерял.

    Хранятся сами слова, а не числа: читать замечание надо глазами — «GitHub»
    говорит о движке больше, чем «одно из одного».
    """

    expected: list[str] = field(default_factory=list)
    distorted: list[str] = field(default_factory=list)

    @property
    def share(self) -> float:
        """Доля искажённых. Записи без имён дают ноль, а не единицу."""
        if not self.expected:
            return 0.0
        return len(self.distorted) / len(self.expected)


def compare(reference: str, hypothesis: str) -> Names:
    """Сверить имена эталона с тем, что услышал движок.

    Чистая функция без вызовов наружу: её гоняют быстрые тесты, а прогон
    зовёт её после каждой расшифровки.
    """
    heard = set(checks.words(hypothesis))
    expected = checks.proper_names(reference)

    return Names(
        expected=expected,
        # Имя считается услышанным, если **все** его части нашлись в расшифровке.
        # Сравнение по множеству, а не по числу вхождений: движок вправе
        # услышать повтор один раз, и это не потеря имени.
        distorted=[
            name for name in expected if any(part not in heard for part in checks.parts(name))
        ],
    )


def corpus_share(reports: list[Names]) -> float:
    """Доля искажённых имён по корпусу.

    Имена складываются по всему набору, а не усредняются по записям: иначе
    запись с одним потерянным именем весила бы столько же, сколько запись
    с четырьмя целыми. Та же причина, по которой `corpus_wer` складывает
    ошибки и слова.
    """
    expected = sum(len(item.expected) for item in reports)
    distorted = sum(len(item.distorted) for item in reports)
    return distorted / expected if expected else 0.0
