#!/usr/bin/env bash
# PreCompact: предупреждение о переполнении контекста.
#
# Сжатие теряет детали. Почти всегда лучше закрыть задачу, сделать /clear
# и начать следующую с чистого контекста — так и решения принимаются
# на полном понимании, а не на пересказе пересказа.

set -uo pipefail

cat >/dev/null

jq -n '{
  systemMessage: "Контекст переполняется. Если текущая задача близка к концу — доведите её и начните следующую с /clear: сжатие теряет детали, а решения на пересказе принимаются хуже."
}'

exit 0
