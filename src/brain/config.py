"""Конфигурация приложения.

Единственное место, где читается окружение. Секретов в коде нет — инвариант 6.

С Фазы 1 приложение обязано падать на старте, если не заданы токен бота или
ключ Google: молча стартовавший процесс без бота выглядит живым и отлаживается
часами. Ошибка называет переменные по именам, а не показывает трейс pydantic.
"""

from functools import lru_cache
from pathlib import Path
from typing import Annotated, Literal

from pydantic import Field, ValidationError, field_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict


class ConfigError(RuntimeError):
    """Окружение задано неполно или неверно. Поднимается один раз, при старте."""


class Settings(BaseSettings):
    """Настройки, собранные из переменных окружения и `.env`."""

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
        frozen=True,
    )

    # --- Окружение ---
    brain_env: Literal["dev", "prod"] = "dev"

    # Таймзона владельца. Нужна напоминаниям: «завтра в 10» — это десять утра
    # там, где он живёт, а не в UTC, в котором живёт сервер. С Фазы 4 она же
    # решает, когда наступило 09:00 для утренней сводки и когда кончились сутки
    # для бюджета касаний, — поэтому неверное значение здесь проявляется
    # не ошибкой, а сообщением не в то время.
    brain_timezone: str = "Europe/Rome"

    # --- База ---
    # Драйвер только асинхронный: синхронного подключения в проекте нет нигде,
    # включая Alembic.
    database_url: str = "postgresql+asyncpg://brain:brain@localhost:5432/brain"

    # --- Telegram ---
    # Обязателен: без него бот не поднимется, и узнать об этом надо на старте.
    telegram_bot_token: str = ""

    # Whitelist отправителей. Пустой список означает «никого не пускаем»:
    # безопасный дефолт важнее удобства, забытая переменная не должна
    # незаметно открыть бота всему миру. Бот предупреждает об этом в логе —
    # молчащий бот и бот, который всех игнорирует, снаружи неотличимы.
    #
    # NoDecode отключает разбор значения как JSON — переменная задаётся
    # человеком в виде `123,456`, а не `[123, 456]`.
    telegram_allowed_user_ids: Annotated[list[int], NoDecode] = Field(default_factory=list)

    # --- Google AI Studio ---
    # Один ключ на два назначения: расшифровка голоса (Фаза 1) и эмбеддинги (Фаза 2).
    google_api_key: str = ""

    # --- Расшифровка голоса (ADR-0007, ADR-0009) ---
    stt_provider: Literal["gemini"] = "gemini"
    # Версия указывается явно. Алиасы вида `gemini-flash-lite-latest` провайдер
    # переставляет на другую модель без предупреждения — вместе с ними уезжает
    # поведение промпта, и архив становится неоднородным незаметно для нас.
    # Имя модели протухает за месяцы: это пункт квартальной проверки.
    stt_model: str = "gemini-3.5-flash-lite"
    # 15 минут — потолок из ADR-0007. Длиннее бот не принимает: резка по паузам
    # добавляет свои ошибки на стыках, и делать её до замера не за чем.
    stt_max_duration_sec: int = 900

    # --- Эмбеддинги (ADR-0006) ---
    embedding_provider: Literal["gemini"] = "gemini"
    # Имя явное, по той же причине, что и у расшифровки: алиас уезжает вместе
    # с поведением, и архив становится неоднородным незаметно для нас.
    #
    # `gemini-embedding-2` — кандидат к сверке, но сверяется он на eval-наборе
    # ретривала, а не по описанию. Отличие, найденное вызовом 18.08.2026:
    # он отдаёт нормированный вектор на всех размерностях, а `001` на срезе
    # до 768 — с нормой ≈0.58. Нормировкой занимается `core/retrieval`,
    # поэтому смена модели на это не влияет.
    embedding_model: str = "gemini-embedding-001"
    # Сколько запросов в сутки даёт бесплатный тир **этой модели**. Наблюдение
    # 20 августа 2026: на 1001-м запросе провайдер ответил `429`, и воркер
    # не поднялся.
    #
    # Число **наблюдённое, а не вычитанное из документации**, и провайдер его
    # меняет: держать его настройкой дешевле, чем ловить следующий 429 вслепую.
    # `None` означает «лимит неизвестен» — тогда `/status` показывает расход
    # без остатка, а не выдумывает остаток.
    #
    # С 26.08.2026 это **поправка к модели из `EMBEDDING_MODEL`**, а не число
    # на весь тир: лимит провайдер считает на модель (см. `core/llm/limits`),
    # и настройка сильнее таблицы известных лимитов в коде.
    embedding_daily_quota: int | None = 1000

    # --- Разметка, дешёвый тир (ADR-0004, ADR-0011) ---
    enrich_provider: Literal["gemini"] = "gemini"
    # Имя явное, по той же причине, что у расшифровки и эмбеддингов: алиас
    # уезжает вместе с поведением. `gemini-2.5-flash-lite`, на которой строился
    # расчёт в плане, снята с обслуживания 16.08.2026 и отвечает 404.
    #
    # Выбор между 3.5 и 3.1 подтверждается eval'ом классификации, а не прайсом:
    # на 600 записях в месяц разница между ними — пять центов (ADR-0011).
    enrich_model: str = "gemini-3.5-flash-lite"
    # Сколько записей уходит в один вызов. Потолок нужен не ради денег, а ради
    # ответа: пачка на полсотни записей упирается в лимит вывода, и обрыв
    # приходит в виде наполовину разобранного JSON.
    enrich_batch_limit: int = 25
    # Суточный лимит запросов **к модели из `ENRICH_MODEL`**, а не ко всему
    # тексту: с 26.08.2026 известно, что провайдер считает лимит на модель
    # (метрика `GenerateRequestsPerDayPerProjectPerModel-FreeTier` в теле `429`),
    # и одно число на четыре модели складывало несравнимое.
    #
    # `None` — **неизвестен**, и выдумывать его нельзя: число из головы
    # в `/status` читалось бы как измеренное. Для `3.5-flash-lite` он так
    # и не измерен — известно только, что он больше двадцати.
    #
    # Настройка живёт дальше как **поправка**: известные лимиты лежат таблицей
    # в `core/llm/limits`, а это число их перебивает — увидев настоящую границу,
    # владелец правит `.env`, а не код. Если поправка окажется не нужна ни разу,
    # обе (`ENRICH_DAILY_QUOTA` и `EMBEDDING_DAILY_QUOTA`) снимаются одним
    # решением владельца, а не молча.
    enrich_daily_quota: int | None = None

    # --- Слой представления (ADR-0015) ---
    # С каким текстом работает система: разметка, отрезки, чанки, индекс.
    # Показ владельцу переключением не управляется вовсе — он всегда идёт
    # по вычищенному тексту, если тот есть.
    #
    # `verbatim` по умолчанию не из осторожности, а по оси 3 ADR-0015:
    # потерянное чисткой из дословного текста никуда не денется и останется
    # находимым, а из индекса исчезнет молча — и проверить это будет нечем,
    # потому что не находится именно то, о существовании чего не знаешь.
    # Переключается **после** `just eval-cleanup` — и не только после него:
    # команды полного перепрогона в проекте пока нет. `just reindex`
    # и `just reenrich` её не заменяют, они отбирают только непосчитанное:
    # первая — записи без чанков или без вектора, вторая — неразмеченное.
    # Поэтому переключение сегодня оставит архив посчитанным над дословным
    # текстом, а отрезки уже заведённых дел начнут резать вычищенный.
    present_working_text: Literal["verbatim", "clean"] = "verbatim"

    # Чем чистится расшифровка. Выбрана сравнением 26.08.2026: `3.6-flash` дала
    # **0.89 записей без замечаний против 0.70** у `3.5-flash-lite`, имён
    # не трогает и слов не выдумывает. До этого здесь стояла `3.5-flash-lite`,
    # и стояла не по качеству, а по единственности — она одна прошла архив
    # целиком, пока лимит бесплатного тира (20 запросов в сутки на модель)
    # не давал домерить соседние.
    #
    # Отдельная настройка, а не `enrich_model`: разметка и чистка — разные
    # задачи с разной ценой ошибки, и выбирать модель им надо порознь.
    cleanup_model: str = "gemini-3.6-flash"
    # Уровень рассуждения у модели чистки. `None` — **не задан**, и это не то же
    # самое, что «уровень по умолчанию»: не задан значит, что про уровень
    # провайдеру не говорится вовсе и тело запроса остаётся прежним.
    #
    # **Почему настройка, а не константа.** Словарь уровней принадлежит
    # провайдеру и уже разный у соседних моделей: `gemini-3.7-flash` отвечает
    # `400 Thinking level MINIMAL is not supported for this model`,
    # а у `gemini-3.5-flash-lite` `minimal` стоит умолчанием (проверено живыми
    # вызовами 25.08.2026). Константа в коде означала бы, что смена
    # `CLEANUP_MODEL` — правка кода, а она задумана как правка `.env`; ровно
    # по этой же причине настройкой сделан `EMBEDDING_DAILY_QUOTA` (ADR-0014).
    #
    # Тип — свободная строка, а не `Literal`. Перечисление здесь было бы нашей
    # догадкой о чужом словаре, замороженной в коде: оно запретило бы уровень,
    # который провайдер заведёт завтра, и устарело бы молча. Неверное значение
    # ловит проба при старте — одной строкой в логе и без остановки воркера.
    cleanup_thinking_level: str | None = None
    # Сколько ждать чистку, прежде чем показать дословный вариант.
    #
    # **Это не задержка показа, а срок запасного пути.** Сообщение
    # перерисовывается сразу, как чистка пришла, — её собственным заданием;
    # отложенное `show-transcript` первым делом смотрит, есть ли уже
    # `clean_text`, и молчит, если есть (`core/scheduler/jobs.show_transcript`).
    # Значит большее число в хороший день не стоит ничего: чистка выигрывает
    # гонку и рисует сама. Оно стоит только тогда, когда чистка застряла или
    # упала, — владелец дольше смотрит на «Принял» без текста.
    #
    # Шестьдесят выбраны владельцем 26.08.2026 из этого соображения, а не из
    # латентности: меньшее число — это мигание, когда дословный текст успевает
    # показаться и через секунды подменяется вычищенным. У `gemini-3.6-flash`
    # медиана 18.4 с в плохой день против ~6 в хороший, то есть пятнадцать
    # мигали бы на большинстве записей плохого дня.
    #
    # Замером это число **не подтверждено и подтверждено быть не может одним
    # днём**: 25.08 те же 70 записей дали максимум 11.6 с, 26.08 — 62.7 с,
    # потому что провайдер отвечал `503 high demand`. День меряется, а не
    # система.
    cleanup_wait_sec: int = 60
    # Чем называются дела и петли. **Своя настройка, а не наследование
    # `CLEANUP_MODEL`**, хотя сегодня в них стоит одна и та же модель.
    # Причина в цене ошибки: вычищенный текст лежит рядом с дословным
    # и переписывается следующим прогоном, а название хранится в базе
    # и показывается владельцу месяцами. Модель, склонная переписывать имена,
    # в названиях опаснее, чем в чистке, — и снимать её надо, не трогая чистку.
    #
    # Проверки при старте у этой модели нет намеренно, в отличие от чистки:
    # бесплатный тир даёт 20 запросов в сутки на модель, а воркер
    # в разработке перезапускается по десятку раз в день — проба съедала бы
    # половину дневного бюджета названий. Неверное имя видно первой же строкой
    # в логе разметки, и разметку оно не роняет (`core/scheduler/jobs.enrich`).
    titles_model: str = "gemini-3.6-flash"

    # Чем пишется лид утренней сводки. **Своя настройка**, как у чистки
    # и названий, хотя сегодня во всех трёх стоит одна модель. Причина
    # та же: снимать их надо порознь. Чистка зовётся на каждое голосовое
    # (8 запросов в живой день), названия — пачкой (~6), сводка — **один раз
    # в сутки**; итого 15 из 20 бесплатного тира, и первой под квотой
    # придерживается та, что дороже, а не та, что оказалась в общей настройке.
    #
    # Пробы при старте у этой модели нет — по той же причине, что у названий:
    # воркер в разработке перезапускается по десятку раз в день, и проба съела
    # бы дневной бюджет сводок целиком. Неверное имя видно первой же строкой
    # в логе касаний, и касания оно не роняет: сводка уходит сухим рендером.
    digest_model: str = "gemini-3.6-flash"
    # Что в сводке идёт первым — дела или петля.
    #
    # **Настройка появляется, а значение остаётся за владельцем.** ADR-0015
    # записал это ценой решения: петля названа ядром системы (`vision.md`
    # §5.2), и внизу сообщения её увидят последней; но и дела внизу — это
    # список, до которого не дошли. Данных нет ни за одно, поэтому выбирает
    # наблюдение, а не автор.
    #
    # Дефолт — **прежний порядок**, тот, что был в `render.morning` до Задачи 7:
    # настройка, поменявшая вид сообщения молча, была бы ответом на вопрос,
    # который она задаёт.
    digest_order: Literal["deeds_first", "loop_first"] = "deeds_first"

    # Выключатель. Нужен ровно на два случая: кончилась квота надолго
    # и владелец хочет видеть дословный текст без ожидания, либо чистка
    # оказалась хуже дословного варианта и её надо снять до нового замера.
    # Выключённая чистка возвращает поведение до Фазы 5: показ сразу
    # и дословно.
    cleanup_enabled: bool = True

    # --- Аудио ---
    # Каталог рядом с репозиторием, а не в нём: файлы голосовых в git не место.
    audio_dir: Path = Path("var/audio")
    # Окно на случай смены STT-модели и перепрогона (ADR-0007). Текст — вечно.
    audio_retention_days: int = 30

    @field_validator(
        "embedding_daily_quota",
        "enrich_daily_quota",
        "cleanup_thinking_level",
        mode="before",
    )
    @classmethod
    def _empty_means_unknown(cls, value: object) -> object:
        """Пустая строка в `.env` — это «неизвестно», а не ошибка.

        `ENRICH_DAILY_QUOTA=` без значения — естественный способ сказать
        «лимита не знаю», и он обязан работать: иначе приложение падает
        на старте из-за переменной, оставленной пустой намеренно. Ровно
        та мина, которую чинит ADR-0014, только с другой стороны.

        У `CLEANUP_THINKING_LEVEL` то же самое, но мина злее: пустая строка
        доехала бы до тела запроса и провайдер отверг бы её `400`. Строка
        в `.env`, оставленная пустой, обязана значить «не задан».
        """
        if isinstance(value, str) and not value.strip():
            return None
        return value

    @field_validator("telegram_allowed_user_ids", mode="before")
    @classmethod
    def _parse_user_ids(cls, value: object) -> object:
        """Разобрать `123,456` в список чисел."""
        if isinstance(value, str):
            return [part.strip() for part in value.split(",") if part.strip()]
        return value


# Переменные, без которых приложение не работает, и объяснение зачем каждая.
# Проверяются отдельно от pydantic: пустая строка для него валидна, а для нас нет.
REQUIRED: dict[str, str] = {
    "TELEGRAM_BOT_TOKEN": "токен бота у @BotFather — без него бот не поднимется",
    "GOOGLE_API_KEY": "ключ Google AI Studio — им расшифровывается голос",
}


def _check_required(settings: Settings) -> None:
    """Упасть, назвав незаполненные переменные по именам."""
    missing = [
        f"  {name} — {why}"
        for name, why in REQUIRED.items()
        if not getattr(settings, name.lower()).strip()
    ]
    if missing:
        raise ConfigError(
            "Не заданы обязательные переменные окружения:\n"
            + "\n".join(missing)
            + "\n\nЗаполнить в .env (образец — .env.example)."
        )


@lru_cache
def get_settings() -> Settings:
    """Настройки процесса. Кэшируются: окружение за время жизни не меняется.

    Обязательные ключи здесь не проверяются намеренно: этой функцией пользуются
    Alembic и тесты, которым нужен только `database_url`. Требовать токен бота
    ради `alembic upgrade head` — способ научить всех держать в окружении
    фальшивый токен, после чего проверка перестанет что-либо значить.
    """
    try:
        return Settings()
    except ValidationError as error:
        raise ConfigError(f"Окружение задано неверно:\n{error}") from error


def get_runtime_settings() -> Settings:
    """Настройки для долгоживущего процесса: бота и воркера.

    Единственная точка, где проверяются обязательные ключи. Оба процесса
    вызывают её первой строкой и падают с внятным текстом, если чего-то нет:
    бот, который поднялся без токена, выглядит работающим и отлаживается часами.

    Наружу ошибка уходит как `SystemExit`, а не как исключение: над трейсбеком
    на двадцать кадров сообщение «заполните .env» теряется, а это единственное,
    что нужно прочитать.
    """
    try:
        settings = get_settings()
        _check_required(settings)
    except ConfigError as error:
        raise SystemExit(f"\n{error}\n") from None
    return settings
