"""Зависимости FastAPI.

Обёртки над хранилищем живут здесь, а не в `storage`: слой хранилища ничего
не знает про веб-фреймворк. Побочная польза — эти зависимости подменяются
в тестах, поэтому быстрый прогон обходится без живой базы.
"""

from brain.storage import db


async def database_is_reachable() -> bool:
    """Отвечает ли база."""
    return await db.ping()
