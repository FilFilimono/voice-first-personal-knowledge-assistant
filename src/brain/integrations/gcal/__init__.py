"""Google Calendar: OAuth, транспорт и четыре вызова REST.

SDK Google в проект намеренно не приходит — ADR-0016, ось 1. Довод не «правило
ADR-0009 так говорит», а размер рабочей поверхности: после разовой авторизации
от всего OAuth остаётся **один POST** на обновление access token, а дальше
обычный REST с заголовком `Authorization: Bearer`. Платить за этот POST
синхронным `requests` внутри async-воркера дороже, чем его написать.

Модулей четыре, и делятся они по тому, **когда исполняются**:

- `errors` — что означает код отказа Google. Своя лестница, а не общий
  `provider_errors.advice`: тот советует править `GOOGLE_API_KEY`, а у календаря
  учётные данные другие, и совет отправил бы владельца не в тот файл;
- `auth` — рабочий режим: access token по refresh token, с кэшем и запасом;
- `client` — четыре вызова REST за портом `ports.Calendar`;
- `authorize` — **одноразовый скрипт** (`just calendar-auth`), который в проде
  не исполняется никогда: он открывает браузер, а на сервере браузера нет.

Что система **не сможет** ни при каком коде — записано в ADR-0016, ось 2,
и это ограничение навсегда, а не недоделка: правки и удаления события
в личном календаре владельца нет, потому что выданных прав на них не хватает.
"""

