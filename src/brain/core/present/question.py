"""Вопрос раскачки, написанный моделью. Место под полный режим Фазы 4.

**По умолчанию сюда не заходят.** Вопрос собирает шаблон кода
(`core/digest/prompting`), и это минимальный режим, записанный в плане Фазы 4:
бесплатный тир даёт 20 запросов в сутки на модель, из них 16 уже заняты чисткой,
названиями и лидом сводки. Ветка живёт за выключенным флагом
`prompting.WRITTEN` — и **пишется вместе с ним**, а не после: выключенная
настройка без кода за ней это обещание, которое некому выполнить, а ветка,
которую ни разу не звали, — почерк `loops.is_stuck`, стоивший проекту месяца
неработавшей смены вопроса у петли.

Разделение труда прежнее (ADR-0015, п. 5), и оно здесь жёстче, чем где-либо
ещё в проекте:

    решает код                              пишет модель
    какой приём применить и к каким данным  одну фразу — сам вопрос
    отбор темы, дела, цитаты                —
    порог, слот, частота, молчание          —
    падение обратно на шаблон               —

**Модель не выбирает, о чём спрашивать.** Ей дают уже выбранный приём и уже
отобранные данные — и просят сказать это по-русски так, как код не умеет.
Это принцип 12 `vision.md` целиком: отбор кодом, речь моделью.

**Правила промпта взяты из разбора источников, а не из вкуса**
(`docs/prompting_sources.md`): один вопрос в сообщении (§1.3), факт без ярлыка
(§4.2), выбор вместо требования (§1.2), спрашивать про то, что во власти
владельца (§2.3), никаких шкал и счётчиков (§1.5 п.8 против `vision.md` §7.0
п.5). Запрет стоит первой строкой — как в чистке, названиях и лиде, и по той
же причине: запрет после задачи читается моделью как пожелание.

**Наружу ходим через `core/llm`.** Инвариант 5 держится дверью, а не вызывающим
кодом; в отбор при этом приватное не попадает вовсе — цитата берётся запросом
с `~is_private_now()` (решение владельца № 4).
"""

import logging
from collections.abc import Sequence
from datetime import datetime
from typing import Any

from brain.core import llm
from brain.core.ports import EntryText, LanguageModel
from brain.core.present import guard
from brain.core.present.pacing import cosmetic_allowed

logger = logging.getLogger(__name__)

# Назначение вызова в `llm_calls`. Своё, как у чистки, названий, сводки
# и связей: вопрос «сколько стоит раскачка» без метки не спросить, а спросят
# его ровно в тот день, когда кончится квота.
PURPOSE = "prompting"

# Разброс не нужен: вопрос пишется по одному конкретному факту, и «другой
# вариант того же вопроса» не значит ничего.
TEMPERATURE = 0.0

# Потолок написанного. Вопрос, а не абзац: длинный вопрос читается как речь
# бота о себе, а не как обращение.
WORD_BUDGET = 25

# Сколько символов каждого факта уходит модели. Медиана расшифровки 409,
# средняя 544 — большинство записей уезжает целиком.
CONTEXT = 600

PROMPT = """Ты пишешь **один** вопрос, которым бот начинает разговор с владельцем.

ГЛАВНОЕ ПРАВИЛО: вопрос ровно один. Два вопроса подряд превращают разговор
в допрос, и отвечают на них молчанием.

Форма: сначала факт из данных, потом открытый вопрос или развилка. Факт
называет то, что произошло, и никогда не называет человека: «за три дня ни
одной записи про учёбу — застряло или отпало?» можно, «ты забросил учёбу»
нельзя. Разница не в резкости, а в том, требует вопрос отчёта или предлагает
разговор.

Спрашивай про то, что во власти владельца одного. «Почему созвон не
состоялся» — вопрос про чужое действие, и он мёртвый; «что ты успел со своей
стороны» — живой.

Нельзя: оценок человека и ярлыков, даже похвальных; советов и «тебе надо»;
шкал, процентов, счётчиков и серий; чисел, дат и имён, которых нет во входе;
подбадриваний; кавычек-ёлочек вокруг всего вопроса и значков; слов
«расскажи мне больше» и «что для тебя важно» — так говорит психолог из кино,
и это слышно.

Тебе дают приём, который надо применить, и данные, к которым он применяется.
Приём менять нельзя — выбран он кодом по архиву."""


def response_schema() -> dict[str, Any]:
    """Схема ответа. Одно поле: модель пишет один вопрос и больше ничего."""
    return {
        "type": "object",
        "properties": {"question": {"type": "string"}},
        "required": ["question"],
    }


async def written(
    model: LanguageModel | None,
    *,
    method: str,
    fallback: str,
    facts: Sequence[str],
    now: datetime,
) -> str | None:
    """Вопрос от модели. `None` — показывается шаблон кода.

    `None` возвращается в шести случаях, и все шесть законные: писать некому,
    данных нет, косметика придержана квотой, модель не ответила, ответ отверг
    гвард, ответ спрашивает не один раз. Второй попытки нет намеренно: она
    стоит второго запроса под квотой в момент, когда первый уже показал,
    что что-то не так.

    `fallback` уезжает в модель как образец приёма, а не как текст на замену:
    без него «приём 4» — это слово, а с ним видно, чего от вопроса хотят.
    """
    if model is None or not facts:
        return None

    if not await cosmetic_allowed(now):
        # Под квотой косметика замолкает первой (ADR-0015, п. 6). Раскачка
        # при этом придёт: шаблон стоит ноль запросов.
        return None

    entries = [
        EntryText(entry_id=number, text=_short(fact), is_private=False)
        for number, fact in enumerate([f"приём · {method}", f"образец · {fallback}", *facts], 1)
    ]

    try:
        completion = await llm.complete_over_entries(
            model,
            entries=entries,
            system=f"{PROMPT}\n\nДлина: не больше {WORD_BUDGET} слов.",
            schema=response_schema(),
            temperature=TEMPERATURE,
            purpose=PURPOSE,
        )
    except Exception:
        # Отказ модели стоит формулировки, а не вопроса: он уйдёт шаблоном.
        logger.exception("вопрос раскачки не написан — уйдёт шаблон")
        return None

    phrase = " ".join(str(completion.data.get("question", "")).split())
    if phrase.count("?") != 1:
        # Ни одного вопроса — это не вопрос; два — ловушка допроса
        # (`docs/prompting_sources.md`, §1.3). И то и другое чинится шаблоном.
        logger.info("вопрос отвергнут (спрашивает не один раз): %r", phrase[:120])
        return None

    refusal = guard.check(
        guard.Written(lead=phrase),
        # Идентификаторов модель не возвращает вовсе: она пишет одну строку.
        expected_ids=(),
        source_digits=guard.digits(" ".join(f"{item.entry_id} {item.text}" for item in entries)),
        word_budget=WORD_BUDGET,
    )
    if refusal is not None:
        logger.info("вопрос отвергнут (%s): %r", refusal, phrase[:120])
        return None

    return phrase


def _short(text: str) -> str:
    """Одной строкой и в пределах потолка — переносы уехали бы в конверт пачки."""
    return " ".join(text.split())[:CONTEXT]


__all__ = ["CONTEXT", "PROMPT", "PURPOSE", "WORD_BUDGET", "response_schema", "written"]
