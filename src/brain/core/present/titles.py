"""Названия дел и петель: то, что владелец читает в сводке вместо обрезка.

ADR-0015, п. 4. До этой задачи дело показывалось первыми семьюдесятью
символами смысловой единицы, обрезанными по счётчику, — то есть куском
собственной речи владельца, начинающимся с «Вот это по боту. В целом всё…».
Ни одна строка сводки не была написана для него.

**Отдельным вызовом, а не полем в схеме разметки.** Причина в ADR-0015, ось 4,
и она не про удобство: правка промпта разметки обнулила бы числа ADR-0011
и ADR-0012 сразу, а два прогона при температуре 1.0 написали бы два разных
названия — и понадобилось бы правило их сведения. Здесь прогон один,
температура ноль, а промпт разметки не тронут вовсе.

**Одним вызовом на пачку, а не вызовом на дело.** Бесплатный тир даёт
20 запросов в сутки **на модель**, и при живом темпе (8 голосовых в день)
чистка съедает 8 из них. Названия по одному на дело не поместились бы
в остаток ни в какой день; пачкой они стоят порядка шести запросов.

**Дела и петли называются порознь.** Идентификатор в конверте `[id] текст`
собирает дверь `core/llm`, и он должен однозначно указывать на строку базы:
дело № 5 и петля № 5 — разные вещи. Смешать их в одной пачке значило бы
получить ответ, про который неизвестно, к чему он относится. Петля при этом
одна на весь архив, так что лишний запрос случается редко и только когда она
без названия.

**Отказ ничего не ломает.** Модель не ответила, ответила не тем, гвард отверг
— во всех трёх случаях названия просто нет, а дело показывается прежним
обрезком и из сводки не исчезает. Это записано в ADR-0015 («расхождение —
прежний сухой рендер») и держится тем, что колонка nullable.
"""

import logging
from collections.abc import Mapping, Sequence
from typing import Any

from brain.core import llm
from brain.core.ports import EntryText, LanguageModel
from brain.core.present import guard, repository
from brain.core.present.repository import COMMITMENT, LOOP, TitleTarget

logger = logging.getLogger(__name__)

# Назначение вызова в `llm_calls`. Своё, как у чистки: вопрос «сколько стоят
# названия» без метки не спросить, а он понадобится ровно в тот день, когда
# кончится квота.
PURPOSE = "titles"

# Разброс здесь только вредит: название пишется один раз и лежит в базе
# месяцами. «Второй вариант того же названия» не значит ничего — в отличие
# от разметки, где расхождение двух прогонов и есть измерительный прибор
# (ADR-0011).
TEMPERATURE = 0.0

# Потолок длины. Семьдесят символов обрезка не помещались в строку сводки
# на телефоне; пятьдесят — то, что читается с одного взгляда, и то, ради чего
# модель зовут. Название длиннее **отвергается, а не подрезается**: подрезка
# по счётчику — ровно тот дефект, от которого уходит эта задача.
MAX_LENGTH = 50

# Сколько дел уходит в один вызов. Ориентир — `enrich_batch_limit` (25), и он
# взят не по привычке: вход у названий короче разметки в разы (смысловая
# единица против записи целиком), а выход — полсотни символов на дело против
# единиц, тем и сущностей. То есть на пачке той же ширины ответ втрое короче
# и обрыв на лимите вывода дальше, чем у разметки.
#
# Больше ставить незачем: 70 открытых дел живого архива это три запроса,
# а не десятки, и весь смысл потолка — в том, чтобы обрыв ответа не приходил
# в виде наполовину разобранного JSON.
BATCH_LIMIT = 25

# Правило первой строкой — как в чистке, и по той же причине: запрет, стоящий
# после задачи, читается моделью как пожелание (замер 19.08.2026 на разметке).
PROMPT = """Ты называешь дело владельца одной короткой строкой.

ГЛАВНОЕ ПРАВИЛО: название состоит из слов записи. Ничего не добавляй от себя —
ни сроков, ни чисел, ни имён, которых в записи нет.

Название: глагол в инфинитиве и предмет, до 50 символов. «Досмотреть фильм»,
«Починить поиск», «Отправить резюме ментору».

Нельзя: вежливых оборотов («не забыть», «постараться»), оценок, упрёков,
кавычек, точки в конце, пересказа всей записи. Если запись про несколько
вещей, назови главную.

Отвечай на каждый пункт, который тебе дали, и ни на один сверх того."""


def response_schema() -> dict[str, Any]:
    """Схема ответа. Провайдер держит её сам — это ограничение, а не просьба.

    Форма повторяет разметку и чистку (`items` с тем же `id`, что во входе),
    потому что конверт пачки собирает общая дверь `core/llm` и он один на всех.
    """
    return {
        "type": "object",
        "properties": {
            "items": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "id": {"type": "integer"},
                        "title": {"type": "string"},
                    },
                    "required": ["id", "title"],
                },
            }
        },
        "required": ["items"],
    }


def requests_for(items: int, *, batch_limit: int) -> int:
    """Сколько запросов уйдёт на столько дел. Нужно командам обслуживания.

    Один прогон на пачку, а не два: состояние из расхождения считает разметка,
    а название сравнивать не с чем.
    """
    if items <= 0:
        return 0
    return -(-items // batch_limit)


def parse(data: dict[str, Any], *, sources: Mapping[int, str]) -> dict[int, str]:
    """Названия, которые годятся к записи в базу.

    Три отсева, и каждый деградирует одинаково — в отсутствие названия,
    то есть в прежний обрезок:

    - **чужой идентификатор.** Та же защита, что в разметке и чистке: в пачке
      номера идут подряд, ошибиться на единицу легко. Здесь она дороже — чужое
      название уедет в базу и будет показываться месяцами;
    - **проверка гварда.** Выдуманное число или имя, упрёк, длина;
    - **ответ не по схеме.** Пусто, а не исключение: название не стоит разметки,
      в транзакции которой оно заводится.
    """
    named: dict[int, str] = {}
    for raw in data.get("items", []):
        try:
            item_id = int(raw["id"])
            title = str(raw["title"]).strip()
        except (KeyError, TypeError, ValueError):
            logger.warning("название не разобрано: %s", str(raw)[:200])
            continue

        source = sources.get(item_id)
        if source is None:
            logger.warning("название для чужого номера %s — отброшено", item_id)
            continue

        refusal = guard.check_title(title, source=source, max_length=MAX_LENGTH)
        if refusal is not None:
            logger.info("название %s отвергнуто (%s): %r", item_id, refusal, title[:80])
            continue

        named[item_id] = title
    return named


async def name(model: LanguageModel, targets: Sequence[TitleTarget]) -> int:
    """Назвать то, что дали. Вернуть, скольким названия проставлены.

    Пачки нарезаются **внутри вида**: дела с делами, петли с петлями — см.
    модуль.

    Отказ провайдера отсюда уходит наверх, а не глотается: в двух местах,
    которые это зовут, обходятся с ним по-разному. Воркер молчит и живёт
    дальше — названия не стоят разметки (`jobs._name_fresh`). Команда
    обслуживания обязана сказать вслух: владелец запустил её руками и ждёт
    ответа, а `429` посреди прогона означает, что остаток дня названий
    не будет и продолжать незачем.
    """
    named = 0
    for kind in (COMMITMENT, LOOP):
        batch = [target for target in targets if target.kind == kind]
        for start in range(0, len(batch), BATCH_LIMIT):
            named += await _name_batch(model, kind, batch[start : start + BATCH_LIMIT])
    return named


async def _name_batch(model: LanguageModel, kind: str, batch: Sequence[TitleTarget]) -> int:
    """Один вызов на одну пачку одного вида."""
    if not batch:
        return 0

    completion = await llm.complete_over_entries(
        model,
        # `entry_id` двери — это идентификатор **дела**, а не записи: у одной
        # записи бывает три дела, и номера записей в пачке повторились бы.
        # Признак приватности при этом настоящий, от исходной записи, поэтому
        # дверь по-прежнему откажет, если приватное просочилось мимо отбора.
        entries=[
            EntryText(entry_id=target.id, text=target.text, is_private=target.is_private)
            for target in batch
        ],
        system=PROMPT,
        schema=response_schema(),
        temperature=TEMPERATURE,
        purpose=PURPOSE,
    )

    named = parse(completion.data, sources={target.id: target.text for target in batch})
    written = await repository.save_titles(kind, named)
    logger.info("названий проставлено: %s из %s (%s)", written, len(batch), kind)
    return written


async def name_open(
    model: LanguageModel, *, limit: int | None = None, recompute: bool = False
) -> int:
    """Назвать открытые дела и петли, которым названия не хватает.

    `limit` — сколько штук взять за раз. Он нужен обоим зовущим и по разным
    причинам: воркеру — чтобы разметка одной записи не утащила в модель весь
    накопленный архив (три запроса вместо одного, и всё это под суточным
    лимитом в двадцать), команде обслуживания — чтобы владелец мог разложить
    прогон на несколько дней.
    """
    return await name(model, await repository.targets_to_name(recompute=recompute, limit=limit))


async def pending(*, recompute: bool, limit: int | None) -> list[TitleTarget]:
    """Что было бы названо. Нужно `--dry-run`: цена печатается до работы."""
    return await repository.targets_to_name(recompute=recompute, limit=limit)


