"""Проверка текста модели перед показом: годится или нет.

Ось 5 ADR-0015 куплена ровно этим модулем. Модель пишет то, что читает
владелец, значит в единственное ежедневное сообщение входит
недетерминированность; съедена она **проверкой, а не обещанием**. Любое
расхождение — прежний сухой рендер, без второй попытки: вторая попытка стоит
второго запроса под квотой в момент, когда первый уже показал, что что-то
не так.

Читателей у гварда два, и правило у них одно. Сводка проверяется целиком
(`check`), название дела или петли — по одному (`check_title`), но
и там и там расхождение означает возврат к прежнему сухому виду: сводка
приходит склейкой строк, дело показывается обрезком. Отдельного места
под проверку названий нет намеренно: правила у них общие, и разъехались бы
две копии молча.

Гвард ничего не правит и не улучшает. Он отвечает «годится» или называет
причину — строкой, которую читает журнал, а не владелец. Чинить текст здесь
было бы третьим автором сообщения после модели и сухого рендера, и через
полгода никто не сказал бы, чьи слова на экране.

**Направление ошибок выбрано намеренно.** Ложный отказ стоит сухой сводки —
владелец получит прежнее сообщение, то самое, что приходило до волны. Ложное
согласие стоит выдуманной даты или упрёка в единственном ежедневном сообщении,
то есть ровно того, из-за чего от таких систем отписываются (`vision.md` §7.0).
Цены несимметричны, поэтому сомнительное отвергается.
"""

import re
from collections.abc import Iterable
from collections.abc import Set as AbstractSet
from dataclasses import dataclass, field

# Слова ретроспективного упрёка — `vision.md` §7.0, принцип 2. Список закрытый
# и лежит на виду: он часть правила, а не деталь реализации, и читаться должен
# рядом с самим правилом.
#
# Правило прохода одно: строка со стоп-словом годится, **только если предлагает
# выбор** — то есть содержит вопросительный знак и союз «или». Трение назвать
# можно («фильм переносится третий день»), но вместе с выходом из него
# («досмотреть или снять?»). Констатация невыполнения без выхода — упрёк,
# сколько бы вежливо она ни звучала.
STOP_WORDS: frozenset[str] = frozenset(
    {
        "накопилось",
        "не сделал",
        "до сих пор не",
        "так и не",
        "опять не",
        "снова не",
        "забыл",
        "висит с",
    }
)

# Число — любая цепочка цифр подряд. Сравнение целыми цепочками, а не по одной
# цифре: иначе «15 сентября» оправдывалось бы годом «2015» из входа, и проверка
# от выдуманных дат защищала бы только на вид.
_NUMBER = re.compile(r"\d+")

# Союз — отдельным словом. Без границ «или» нашлось бы внутри «молили»,
# и любой упрёк проходил бы, стоило рядом оказаться подходящему глаголу.
_CHOICE = re.compile(r"\bили\b")

_SPACES = re.compile(r"\s+")

# Слово — буквы подряд, без цифр и знаков. Цифры разбираются своим выражением,
# и слово с цифрой внутри («Б2») обязано попасть туда, а не сюда.
_WORD = re.compile(r"[^\W\d_]+")

# Сколько первых букв имени сравнивается со входом. Четыре — потому что русский
# меняет у имён окончание, а не начало: «Мишей» и «Мише» совпадают четырьмя
# буквами, а «Миша» и «Маша» расходятся на второй. Число выбрано, а не измерено,
# и это надо знать: замерить его можно будет только на живых названиях.
NAME_STEM = 4


@dataclass(frozen=True)
class Written:
    """То, что написала модель: лид, строка на каждое дело, строка петли.

    Идентификаторы дел — ключи `lines`, а не числа внутри текста. Разбирать
    их из строк было бы гаданием: номер «1.» в сообщении ставит код (ADR-0015,
    п. 5), и отличить его от даты в тексте нечем. Заодно из этого следует, что
    любая цифра в самих строках — либо из входа, либо выдумка, третьего нет.

    Тип живёт здесь, а не рядом со сводкой, потому что первым его требует
    проверка: сводка строится после гварда и на него опирается.
    """

    lead: str
    lines: dict[int, str] = field(default_factory=dict)
    loop_line: str | None = None

    def parts(self) -> list[str]:
        """Всё, что увидит владелец, — в порядке чтения."""
        parts = [self.lead, *self.lines.values()]
        if self.loop_line is not None:
            parts.append(self.loop_line)
        return parts


def reproach(text: str) -> str | None:
    """Найденное слово упрёка или `None`.

    Ловится **по тексту, а не по намерению**: ревизия после недели
    использования нашла нарушение §7.0 п.2 не в замысле, а в готовых строках,
    и увидеть такое может только проверка написанного.

    Единица разбора — строка, а не всё сообщение: выбор, стоящий строкой ниже,
    упрёка не снимает, потому что владелец читает строку целиком и упирается
    в неё раньше, чем доходит до следующей.

    Совпадение ищется подстрокой, поэтому «забыл» поймается и в «забыла»,
    и в «позабыл». Это перебор в сторону отказа, и он выбран сознательно:
    лишний отказ стоит сухой строки, пропуск — упрёка на экране.
    """
    for line in text.splitlines():
        lowered = _SPACES.sub(" ", line).lower()
        found = next((word for word in sorted(STOP_WORDS) if word in lowered), None)
        if found is None:
            continue
        if "?" in line and _CHOICE.search(lowered):
            continue
        return found
    return None


def digits(text: str) -> set[str]:
    """Числа текста целыми цепочками. Ими меряется, что было во входе."""
    return set(_NUMBER.findall(text))


def check_title(title: str, *, source: str, max_length: int) -> str | None:
    """Причина отказа или `None`, если название годится к записи в базу.

    Что взято у сводки и почему.

    **Числа** — целыми цепочками, тем же выражением: выдуманный срок «за 5 дней»
    в названии опаснее, чем в лиде. Лид живёт одно утро, а название лежит
    в базе и показывается месяцами, и владелец прочитает его как срок,
    который сам себе ставил.

    **Упрёк** — тем же стоп-детектором и с тем же правилом «трение можно
    назвать только вместе с выбором». Название пишет модель, а не владелец,
    и «Так и не досмотреть фильм» в утреннем списке — ровно нарушение
    `vision.md` §7.0, принцип 2.

    **Длина** — отказом, а не подрезкой. Подрезанное по счётчику название это
    обрезок, написанный моделью, то есть ровно то, от чего уходит задача.

    Чего у сводки нет и что дописано здесь: **имена**. У лида проверять их
    было не нужно — он пишется по данным, где имён нет вовсе; название пишется
    по тексту записи, и «Написать Мише» при отсутствии Миши в записи —
    выдумка того же рода, что число. Ловятся два вида: слово с большой буквы
    не в начале строки и слово латиницей в любом регистре (`find`, `Navis` —
    так в архиве выглядят имена команд и компаний).

    Сравнение — **по началу слова**, а не буквально. Русский склоняет имена
    («Мишей» → «Мише»), и требовать точного совпадения значило бы отвергать
    каждое второе название с именем, то есть показывать обрезок там, где всё
    в порядке. Направление ошибок при этом прежнее: длинное имя, совпавшее
    первыми буквами с чужим, — цена, которую здесь платят за склонение.
    """
    body = title.strip()
    if not body:
        return "название пустое"

    if len(body) > max_length:
        return f"длина {len(body)} при потолке {max_length}"

    if invented := sorted(digits(body) - digits(source)):
        return f"числа, которых не было во входе: {invented}"

    if strangers := sorted(_unknown_names(body, source)):
        return f"имена, которых не было во входе: {strangers}"

    if word := reproach(body):
        return f"упрёк без выбора: «{word}»"

    return None


def _unknown_names(title: str, source: str) -> set[str]:
    """Имена названия, которых нет во входе."""
    known = _WORD.findall(source)
    return {
        word
        for index, word in enumerate(_WORD.findall(title))
        if _looks_like_name(word, first=index == 0) and not _stem_known(word, known)
    }


def _looks_like_name(word: str, *, first: bool) -> bool:
    """Похоже ли слово на имя.

    Первое слово названия не считается именем никогда: название начинается
    с заглавной буквы по правилам письма, а не потому, что там имя.
    """
    return word.isascii() or (not first and word[:1].isupper())


def _stem_known(word: str, known: list[str]) -> bool:
    """Есть ли во входе слово с тем же началом."""
    stem = word[:NAME_STEM].lower()
    return any(other.lower().startswith(stem) for other in known)


def check(
    written: Written,
    *,
    expected_ids: Iterable[int],
    source_digits: AbstractSet[str],
    word_budget: int,
) -> str | None:
    """Причина отказа или `None`, если текст годится к показу.

    `source_digits` — числа, которые были во входе модели: возраст дела,
    сколько раз откладывали, время. Всё, чего в этом наборе нет, считается
    выдумкой, а не связкой: дата, взявшаяся из ниоткуда, в сводке неотличима
    от настоящей и потому опаснее пустой строки.

    `word_budget` меряет **написанное моделью**, без нумерации и кнопок:
    их ставит код и считает сам. Сорок секунд из ADR-0015 — проверяемый
    бюджет, а не пожелание, и проверяется он здесь.
    """
    if not written.lead.strip():
        return "лид пустой"

    expected = set(expected_ids)
    got = set(written.lines)
    if extra := sorted(got - expected):
        return f"в ответе дела, которых не давали: {extra}"
    if lost := sorted(expected - got):
        return f"в ответе потеряны дела: {lost}"

    if blank := sorted(deed_id for deed_id, line in written.lines.items() if not line.strip()):
        return f"пустые строки у дел: {blank}"

    for part in written.parts():
        if invented := sorted(set(_NUMBER.findall(part)) - set(source_digits)):
            return f"числа, которых не было во входе: {invented}"

    for part in written.parts():
        if word := reproach(part):
            return f"упрёк без выбора: «{word}»"

    words = sum(len(part.split()) for part in written.parts())
    if words > word_budget:
        return f"слов {words} при бюджете {word_budget}"

    return None
