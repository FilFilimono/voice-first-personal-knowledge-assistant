"""Признак «это вопрос к архиву, а не новая мысль».

Разбирает **код**, а не модель. Причина та же, по которой кодом разобраны
напоминания (`scheduler/reminders`) и связи (инвариант 8): признак срабатывает
на **каждом** текстовом сообщении, а бесплатный тир даёт 20 запросов в сутки
на модель — из них 15 уже заняты чисткой, названиями и лидом сводки. Вызов
модели на каждое сообщение вынес бы дневной остаток целиком (принцип 12
`vision.md`).

**Незнакомую форму разбор пропустит молча — это осознанная цена.** Список
признаков конечный и написан руками, как `reminders.IMPERATIVE_VERBS`:
«а что там было с курсовой» он поймает, «интересно, я вообще писал про
курсовую» — нет, и владелец увидит только «Записал.». Цена выбрана
сознательно, потому что ошибка в **эту** сторону ничего не стоит: сообщение
всё равно легло записью. Обратная ошибка — потерянная мысль — недопустима,
и поэтому в `adapters/telegram/handlers` поиск показывается **дополнительно
к записи**, а не вместо неё.

Три признака, и все три меряны на живом архиве (85 записей, 06.09.2026):

    начало фразы        `OPENINGS` — ноль ложных срабатываний из 85
    обращение к боту    `ADDRESSED` — ноль ложных срабатываний из 85
    вопросительный знак `MARK_LIMIT` — одно из 85 (запись 23, «всё ли
                        работает?», проверка бота на 31 символ)

Третий признак без ограничения по длине не годился бы вовсе: «?» есть
в 17 записях из 85, то есть в каждой пятой, — живая речь полна риторических
вопросов («ну, а что за зашоренность?»). Все 16 остальных длиннее 120
символов, поэтому граница проведена там.
"""

from dataclasses import dataclass

from brain.storage.models.topic import normalize

# Начала, с которых владелец спрашивает архив. Сравниваются **по словам**,
# а не по подстроке: «что там по» как подстрока совпало бы с «что там политика».
#
# «напомни» здесь нет и быть не должно: с него начинается напоминание
# (`scheduler/reminders`), и перехват увёл бы его в поиск.
OPENINGS: tuple[str, ...] = (
    "что я думал",
    "что я думаю",
    "что я писал",
    "что я говорил",
    "что я решил",
    "что я знаю",
    "что там по",
    "что там с",
    "что там про",
    "что там было",
    "что у меня по",
    "что у меня с",
    "что было по",
    "что известно про",
    "когда я",
    "как менялось",
    "как менялись",
    "о чем я",
    "найди",
    "поищи",
    "покажи",
    "вспомни",
)

# Обращение во втором лице к боту. Стоит где угодно, а не только в начале:
# «а ты помнишь, что я решил по курсовой» — обращение в середине.
ADDRESSED: tuple[str, ...] = (
    "ты помнишь",
    "ты не помнишь",
    "помнишь ли",
    "ты знаешь",
    "ты записывал",
    "что ты помнишь",
    "что ты знаешь",
)

# До какой длины вопросительный знак сам по себе считается вопросом к архиву.
# Число из замера, а не из головы: см. шапку модуля. Медиана живой записи —
# 409 символов, вопрос к архиву («что там по учёбе?») — десятки.
#
# Здесь оно **умолчание, а не решение**: рабочее значение приходит настройкой
# `ARCHIVE_QUESTION_MARK_LIMIT`, потому что снято оно на архиве в 85 записей
# и с его ростом поедет. Умолчание оставлено, чтобы функция читалась и
# проверялась без окружения.
MARK_LIMIT = 120

# Служебные слова, которые остаются после срезанного начала и в запрос не идут:
# «что там **про** учёбу» → искать надо «учёбу».
LEAD_WORDS: tuple[str, ...] = (
    "про",
    "по",
    "с",
    "со",
    "о",
    "об",
    "обо",
    "насчет",
    "тему",
    "теме",
    "мне",
    "там",
)

# Короче этого запрос не запрос: «что там по» без темы искать нечего.
MIN_QUERY = 3

# Что снимается с краёв слова. Кавычки тоже: «что там по «учёбе»?» — это
# та же тема, что и без кавычек.
PUNCTUATION = "?!.,;:—-«»\"'()"


@dataclass(frozen=True, slots=True)
class Asked:
    """Вопрос к архиву: по чему искать и какой признак сработал.

    `signal` уходит строкой в журнал, а не владельцу. Молчание и срабатывание
    механизма, живущего на каждом сообщении, обязаны быть различимы в логе —
    иначе «почему он вдруг ответил поиском» не разобрать (ADR-0013).
    """

    query: str
    signal: str


def asked(said: str, *, mark_limit: int = MARK_LIMIT) -> Asked | None:
    """Что спросили у архива. `None` — это не вопрос, а мысль.

    Слова сравниваются в нормализованном виде (нижний регистр, «ё» → «е»,
    схлопнутые пробелы) — тем же правилом, которым сравниваются имена тем.
    Второго правила нормализации в проекте быть не должно.

    Сам запрос при этом берётся из **исходного** текста: «ё» нужна триграммному
    каналу поиска, а регистр — именам собственным.
    """
    # Пунктуация снимается **до** сравнения, иначе «покажи, что я думал» мимо
    # признака «покажи»: в разговорной записи запятая липнет к слову, а список
    # признаков написан словами. Пары держатся вместе, чтобы номер слова
    # в исходном тексте и в нормализованном совпадал.
    paired = [(word, normalize(word.strip(PUNCTUATION))) for word in said.split()]
    kept = [(word, flat_word) for word, flat_word in paired if flat_word]
    if not kept:
        return None

    original = [word for word, _ in kept]
    flat = [flat_word for _, flat_word in kept]

    for opening in OPENINGS:
        head = opening.split()
        if flat[: len(head)] == head:
            return _asked(original[len(head) :], original, signal=f"начало «{opening}»")

    for address in ADDRESSED:
        found = _index_of(flat, address.split())
        if found is not None:
            tail = found + len(address.split())
            return _asked(original[tail:], original, signal=f"обращение «{address}»")

    if "?" in said and len(normalize(said)) <= mark_limit:
        return _asked(original, original, signal="вопросительный знак")

    return None


def _asked(rest: list[str], whole: list[str], *, signal: str) -> Asked | None:
    """Собрать вопрос из того, что осталось после признака.

    Если после срезанного начала не осталось ничего («покажи?»), запросом
    становится всё сообщение целиком: пустой запрос поиск не выполняет вовсе,
    и признак, сработавший впустую, оставил бы владельца без ответа.
    """
    query = _query(rest) or _query(whole)
    if len(query) < MIN_QUERY:
        return None
    return Asked(query=query, signal=signal)


def _query(words: list[str]) -> str:
    """Слова запроса: без пунктуации и без служебного начала."""
    cleaned = [stripped for word in words if (stripped := word.strip(PUNCTUATION))]
    while cleaned and normalize(cleaned[0]) in LEAD_WORDS:
        cleaned.pop(0)
    return " ".join(cleaned)


def _index_of(words: list[str], phrase: list[str]) -> int | None:
    """С какого слова начинается фраза. `None` — её здесь нет."""
    for start in range(len(words) - len(phrase) + 1):
        if words[start : start + len(phrase)] == phrase:
            return start
    return None
