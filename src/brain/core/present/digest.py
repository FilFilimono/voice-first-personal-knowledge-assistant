"""Лид утренней сводки: единственная строка, которую пишет модель.

ADR-0015, п. 5. Разделение труда здесь такое, и оно не про удобство:

    решает код                      пишет модель
    какие три дела и какая петля    лид — одну конкретную вещь
    порядок, нумерация, кнопки      —
    строка петли                    —
    бюджет слов                     —
    падение на сухой рендер         —

**Модель пишет только лид, а не строки дел** — это уточнение владельца
к таблице ADR. Строки дел уже написаны: у дела есть название (Задача 4),
и переписывать его каждое утро значило бы платить запросом за то, что лежит
в базе. Строка петли остаётся кодом по причине из Задачи 5: кнопка — это
действие, текст — это речь, и вопрос, не совпадающий с кнопками, оставляет
человека без понимания, что нажимать.

**Что уходит в модель и почему именно это.** Три дела с названием, возрастом
и состоянием; вопрос петли; и **записи вчерашнего дня целиком**. Последнее —
не украшение, а смысл задачи: связать сегодняшнее дело с тем, о чём владелец
думал вчера, код не умеет, а модель умеет, и ради этого она здесь. Скупой вход
даёт скупой текст, поэтому вчерашнее передаётся контекстом, а не списком имён.

**Счётчик откладываний петли не передаётся, и это решение владельца.**
«Сдвинулось?» на первой петле — нормальный вопрос, на четвёртой — требование
отчёта у человека, который трижды ответил «ещё думаю». Гвард ловит упрёк
по лексике и упрёк по счётчику поймать не может в принципе: «ты откладывал это
трижды» состоит из безобидных слов. Не зная счётчика, модель не может им
попрекнуть — упрёк становится **невозможен**, а не отлавливается постфактум,
и гвард остаётся чистой функцией от текста, не знающей предметной области.

**Наружу ходим через `core/llm`.** Инвариант 5 держится дверью, а не вызывающим
кодом; приватное при этом не отбирается вовсе (запросом к базе, как в `titles`),
потому что одна просочившаяся запись подняла бы исключение на всю пачку.
"""

import logging
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from datetime import datetime, time, timedelta
from typing import Any
from zoneinfo import ZoneInfo

from brain.core import llm
from brain.core.ports import EntryText, LanguageModel
from brain.core.present import guard, repository
from brain.core.present.pacing import cosmetic_allowed
from brain.core.present.repository import COMMITMENT, LOOP
from brain.storage.models.commitment import CommitmentState

logger = logging.getLogger(__name__)

# Назначение вызова в `llm_calls`. Своё, как у чистки и названий: вопрос
# «сколько стоит сводка» без метки не спросить, а он понадобится ровно в тот
# день, когда кончится квота.
PURPOSE = "digest"

# Разброс здесь не измерительный прибор, в отличие от разметки (ADR-0011):
# лид пишется один раз в сутки, и «второй вариант того же лида» не значит
# ничего. При этом данные каждое утро другие, так что повторяться изо дня
# в день ему не с чего.
TEMPERATURE = 0.0

# Сорок секунд из `vision.md` §5.1 — проверяемый бюджет, а не пожелание.
# Восемьдесят слов на **всё сообщение**, а не на лид: владелец читает то,
# что пришло, а не то, что написала модель. Сколько из них остаётся лиду,
# считает код и говорит модели числом (см. `write`).
WORD_BUDGET = 80

# Сколько дел показывается. «Не больше трёх действий» из ревизии я читаю как
# «не больше трёх дел»; петля — четвёртая, необязательная, и оставлена
# намеренно, потому что она ядро системы (`vision.md` §5.2).
#
# Число живёт здесь, а не в `core/digest/morning`, потому что это правило
# показа, а не отбора: отбирает сводка старейшие, а обрывает список бюджет
# сообщения. `morning.COMMITMENTS_SHOWN` берёт его отсюда — два числа
# разъехались бы молча, и заметить это можно было бы только по длине сводки.
MAX_DEEDS = 3

# Сколько вчерашних записей уходит контекстом. Двадцать — это два живых дня
# (9.4 записи в сутки на замере 24.08.2026), то есть потолок, а не режим:
# он существует, чтобы день, в который владелец наговорил полсотни записей,
# не упёрся в лимит вывода наполовину разобранным ответом.
CONTEXT_ENTRIES = 20

# Сколько символов берётся от каждого текста. Медиана расшифровки 409,
# средняя 544 — большинство записей уходит целиком, а длинная обрезается
# по началу: мысль в голосовой записи стоит в начале, а к концу владелец
# уже проговаривает детали.
CONTEXT_CHARS = 600

# Метки строк во входе. Вынесены в константы, потому что по ним же тесты
# отличают строку петли от строки дела: разбор входа глазами — это то, что
# ломается молча.
DEED_MARK = "дело"
LOOP_MARK = "петля"
CONTEXT_MARK = "вчера"

# Ниже этого лид не написать, и просить нечего. Случается, когда сухие строки
# съели бюджет сами: три длинных названия плюс вопрос петли. Тогда лида
# не будет вовсе — сообщение и без него полное, а вызов под квотой стоит
# столько же, сколько нужный.
LEAD_MIN_WORDS = 6

STATE_WORDS = {
    CommitmentState.OPEN: "открыто",
    CommitmentState.IN_PROGRESS: "в работе",
    CommitmentState.SNOOZED: "отложено",
}

# Правило первой строкой — как в чистке и названиях, и по той же причине:
# запрет, стоящий после задачи, читается моделью как пожелание (замер
# 19.08.2026 на разметке).
PROMPT = """Ты пишешь одну-две фразы в начало утренней сводки — лид.

ГЛАВНОЕ ПРАВИЛО: лид называет одну конкретную вещь. Пересказ количества
(«три дела и один вопрос») запрещён — это владелец видит и без тебя.

Самое ценное, что ты можешь сделать, — связать. Если сегодняшнее дело или
открытый вопрос продолжает то, что владелец записывал вчера, скажи об этом
прямо. Связи нет — не выдумывай её: назови то, что сегодня важнее прочего,
или то, что переносится не первый день.

Где называешь трение, обязан дать выбор. Не «фильм висит третий день»,
а «фильм висит третий день — досмотреть или снять?». Названное невыполнение
без выхода — упрёк, а сообщение даёт, а не требует.

Нельзя: чисел, дат, имён и сроков, которых нет во входе; счётчиков,
процентов, оценок и подбадриваний; повелительного наклонения («сделай»,
«не забудь»); списков, заголовков, кавычек и значков — лид это сплошной текст.

Тебе дают дела (название, сколько висит, состояние), открытый вопрос
и записи вчерашнего дня целиком. Сами дела и вопрос владелец увидит и так,
их писать не надо — ты пишешь только лид."""


@dataclass(frozen=True, slots=True)
class Deed:
    """Дело в том виде, в каком его показывают модели.

    `text` — то, чем дело называется: написанное название, а если его нет —
    снимок смысловой единицы. Владелец увидит его же, только подрезанным
    по ширине строки; модели отдаётся целиком, потому что подрезка по счётчику
    экономит ровно на понимании.
    """

    id: int
    text: str
    created_at: datetime
    state: CommitmentState


@dataclass(frozen=True, slots=True)
class Question:
    """Открытая петля: только формулировка вопроса. Без счётчика — см. модуль."""

    id: int
    text: str


def response_schema() -> dict[str, Any]:
    """Схема ответа. Провайдер держит её сам — это ограничение, а не просьба.

    Одно поле, потому что модель пишет только лид. Форма пачки (`items`
    с идентификаторами) здесь не нужна вовсе: отвечать по каждому пункту входа
    незачем, а идентификатор, который модели не давали возвращать, она
    и не вернёт.
    """
    return {
        "type": "object",
        "properties": {"lead": {"type": "string"}},
        "required": ["lead"],
    }


async def write(
    model: LanguageModel,
    *,
    deeds: Sequence[Deed],
    question: Question | None,
    now: datetime,
    timezone: str,
    words: int,
) -> guard.Written | None:
    """Написать лид. `None` — сводка собирается сухим рендером.

    `None` возвращается в пяти случаях, и все пять — законные состояния,
    а не сбои: показывать нечего, косметика придержана квотой, бюджет слов
    съеден сухими строками, модель не ответила, ответ отверг гвард.

    `words` — сколько слов остаётся лиду. Считает его код, потому что он один
    знает, сколько слов поставит сам: нумерацию, названия дел и строку петли
    владелец прочитает в том же сообщении, и бюджет в сорок секунд общий.
    """
    if not deeds and question is None:
        # Ноль данных — ноль вызовов (ADR-0015, п. 5). Не ради экономии:
        # сводка ни о чём хуже отсутствия сводки.
        return None

    if not await cosmetic_allowed(now):
        # Под квотой косметика замолкает первой, а сводка приходит сухой
        # (ADR-0015, п. 6). Решение принимается здесь, а не у зовущего, потому
        # что зовущий один — в отличие от названий, где их двое и обходятся
        # они с отказом по-разному.
        return None

    if words < LEAD_MIN_WORDS:
        logger.info("лид не запрашивается: бюджет %s слов", words)
        return None

    items, shown = await _input(deeds, question, now=now, timezone=timezone)
    if not shown:
        # Всё, что можно было показать, оказалось приватным. Лиду не о чем
        # писать: вчерашний контекст без дел и петли — это архив без сегодня.
        #
        # Считается числом, а не разбором собранных строк: строка вчерашней
        # записи вполне может начинаться словом «дело», и проверка по тексту
        # однажды приняла бы её за дело.
        logger.info("лид не запрашивается: показывать модели нечего")
        return None

    try:
        completion = await llm.complete_over_entries(
            model,
            entries=items,
            system=f"{PROMPT}\n\nДлина: не больше {words} слов.",
            schema=response_schema(),
            temperature=TEMPERATURE,
            purpose=PURPOSE,
        )
    except Exception:
        # Отказ модели стоит лида, а не сводки: она уйдёт сухим рендером
        # тем же тиком. Исключение отсюда наверх означало бы, что упавший
        # провайдер отменяет единственное ежедневное сообщение.
        logger.exception("лид не написан — сводка уйдёт сухим рендером")
        return None

    written = guard.Written(lead=str(completion.data.get("lead", "")).strip())
    refusal = guard.check(
        written,
        # Идентификаторов модель не возвращает вовсе: строки дел пишет код.
        # Проверка при этом остаётся на месте — она ловит ответ, в котором
        # появилось то, чего не просили.
        expected_ids=(),
        source_digits=_digits(items),
        word_budget=words,
    )
    if refusal is not None:
        logger.info("лид отвергнут (%s): %r", refusal, written.lead[:120])
        return None

    return written


async def _input(
    deeds: Sequence[Deed],
    question: Question | None,
    *,
    now: datetime,
    timezone: str,
) -> tuple[list[EntryText], int]:
    """Собрать вход модели и сказать, сколько в нём сегодняшнего.

    Второе число — дела и петля, дошедшие до пачки. Оно нужно зовущему: если
    всё сегодняшнее оказалось приватным, писать лид не о чем, а посчитать это
    разбором готовых строк было бы гаданием.

    Приватное сюда не попадает.

    Номер в конверте — **порядковый номер строки пачки, а не идентификатор
    базы**. В одну пачку идут три разные таблицы (дела, петли, записи),
    и номер 5 значил бы сразу дело, петлю и запись; у дел он вдобавок тот же,
    каким код пронумерует их в сообщении. Это отличие от `titles`, где
    идентификатор настоящий: там ответ приходит по номеру и должен указывать
    на строку базы, а здесь модель отвечает одним лидом и ни на что не ссылается.

    Приватность отсеивается **запросом**, а не флагом в этой функции: дверь
    `core/llm` на приватную запись поднимает исключение, и одно просочившееся
    дело утащило бы за собой весь вызов.
    """
    items: list[str] = []

    public_deeds = await repository.public_among(COMMITMENT, [deed.id for deed in deeds])
    items += [
        f"{DEED_MARK} · {_short(deed.text)} · {_age(deed, now)} · {_state(deed)}"
        for deed in deeds
        if deed.id in public_deeds
    ]

    if question is not None and question.id in await repository.public_among(LOOP, [question.id]):
        items.append(f"{LOOP_MARK} · {_short(question.text)}")

    # Всё, что относится к сегодняшнему дню, уже собрано: дальше идёт контекст.
    shown = len(items)

    start, end = _yesterday(now, timezone)
    items += [
        f"{CONTEXT_MARK} · {_short(recorded.text)}"
        for recorded in await repository.recorded_between(start, end, limit=CONTEXT_ENTRIES)
    ]

    return [
        EntryText(entry_id=number, text=text, is_private=False)
        for number, text in enumerate(items, start=1)
    ], shown


def _yesterday(now: datetime, timezone: str) -> tuple[datetime, datetime]:
    """Границы вчерашнего дня по календарю владельца.

    По календарю, а не «минус сутки»: сводка приходит утром, и «вчера» для
    владельца — это вчерашний день целиком, а не отрезок от вчерашнего утра.
    """
    zone = ZoneInfo(timezone)
    day = (now.astimezone(zone) - timedelta(days=1)).date()
    start = datetime.combine(day, time.min, tzinfo=zone)
    return start, start + timedelta(days=1)


def _short(text: str) -> str:
    """Одной строкой и в пределах потолка. Переносы уехали бы в конверт пачки."""
    flat = " ".join(text.split())
    return flat[:CONTEXT_CHARS]


def _age(deed: Deed, now: datetime) -> str:
    """Сколько дело висит. Словами, а не датой: дата попросила бы её пересказать."""
    days = (now - deed.created_at).days
    return f"висит {days} дн." if days > 0 else "заведено сегодня"


def _state(deed: Deed) -> str:
    return STATE_WORDS.get(deed.state, deed.state.value)


def _digits(items: Iterable[EntryText]) -> set[str]:
    """Числа, которые были во входе, — вместе с номерами строк конверта.

    Номера считаются наравне с текстом намеренно: их модель видит так же,
    как всё остальное, и запретить ей повторить единицу из «[1]» значило бы
    отвергать лид за слово «один раз».
    """
    return guard.digits(" ".join(f"{item.entry_id} {item.text}" for item in items))


