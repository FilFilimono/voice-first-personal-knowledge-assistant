"""Чистка расшифровки: что спрашивают у модели и как разбирают ответ.

Отдельный вызов по **готовому дословному тексту**, а не второе поле в ответе
расшифровки — ADR-0015, ось 2. Три причины, и первая решающая: промпт
расшифровки не трогается вовсе, значит ненаписанный замер WER (главный долг
Фазы 1) остаётся замером выбранного провайдера, а не смеси. Вторая: отказ
чистки не стоит записи — она падает и ретраится независимо. Третья: модель
чистки выбирается своим замером, а не наследует модель расшифровки.

Цена названа там же: +1 запрос на каждое голосовое, то есть удвоение расхода
квоты на голосовую запись. Квота считается в запросах (ADR-0014), и это
единственный настоящий риск решения — деньги здесь ни при чём.

**Наружу ходим через `core/llm`, а не своим POST.** Там живут проверка
приватности (инвариант 5), учёт в `llm_calls` и маршрутизация тира. Свой вызов
рядом означал бы три копии одного и того же, из которых две однажды отстанут.
"""

import logging
from typing import Any

from brain.core import llm
from brain.core.ports import EntryText, LanguageModel

logger = logging.getLogger(__name__)

# Назначение вызова в `llm_calls`. Ради него таблица и заведена: «сколько
# стоит чистка» без этой метки не спросить, а именно она — треть месячного
# счёта волны.
PURPOSE = "cleanup"

# Разброс здесь только вредит — ровно как в расшифровке, и ровно наоборот
# по сравнению с разметкой, где температура это измерительный прибор
# (состояние считается по расхождению двух прогонов, ADR-0011). У чистки
# прогон один, и «второй вариант того же текста» не значит ничего.
TEMPERATURE = 0.0

# Правило первой строкой — и это не оформление. Модель по умолчанию склонна
# улучшать текст: замер 19.08.2026 на разметке показал, что запрет, стоящий
# после задачи, читается как пожелание и обходится с обоснованием — модель
# завела запрещённую процессную тему и **приложила объяснение, почему можно**.
PROMPT = """Ты приводишь в читаемый вид расшифровку голосовой записи.

ГЛАВНОЕ ПРАВИЛО: лучше недочистить, чем перечистить. При любом сомнении
оставь как есть. Потеря смысла — дефект. Оставшееся «ну» — не дефект.

Убери: слова-паразиты («э», «мм», «ну вот», «это самое»), самоповторы
(«надо надо»), оборванные начала брошенных фраз. Расставь знаки препинания
и заглавные буквы.

Не трогай: смысл, порядок мыслей, лексику, оттенок, отрицания, числа, имена,
даты. Не перефразируй. Не меняй порядок слов. Не исправляй согласования
и падежи. Не дописывай ничего от себя. Слова «наверное», «кажется»,
«по-моему» — это степень уверенности, а не шум: оставь их.

Если чистить нечего, верни текст без изменений."""


def response_schema() -> dict[str, Any]:
    """Схема ответа. Провайдер держит её сам — это не просьба, а ограничение.

    Форма пачки повторяет разметку (`[id] текст` на входе, `items` с тем же
    `id` на выходе), потому что конверт собирает общая дверь `core/llm`
    и он один на всех. Чистка при этом всегда идёт по одной записи: воркер
    чистит по одной, и замер обязан воспроизводить рабочий режим.
    """
    return {
        "type": "object",
        "properties": {
            "items": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "id": {"type": "integer"},
                        "clean": {"type": "string"},
                    },
                    "required": ["id", "clean"],
                },
            }
        },
        "required": ["items"],
    }


def parse(data: dict[str, Any], *, entry_id: int) -> str | None:
    """Вычищенный текст из ответа модели. `None` — если брать нечего.

    Чужой идентификатор отбрасывается, и это та же защита, что в разметке:
    в пачке идентификаторы идут подряд, и ошибиться на единицу легко. Молча
    приняв такой ответ, мы показали бы владельцу чужую запись вместо его —
    здесь это хуже, чем в разметке, потому что подмена уйдёт прямо на экран.

    Пустая чистка — тоже отказ. Деградация обязана быть на дословный текст,
    а не на пустоту: на коротком «ок» модель вполне вернёт `""` или пробел.
    """
    for raw in data.get("items", []):
        try:
            if int(raw["id"]) != entry_id:
                continue
            clean = str(raw["clean"]).strip()
        except (KeyError, TypeError, ValueError):
            logger.warning("чистка не разобрана: %s", str(raw)[:200])
            continue
        if clean:
            return clean

    logger.info("чистка записи %s ничего не дала — покажем дословный вариант", entry_id)
    return None


async def clean_one(
    model: LanguageModel, *, entry_id: int, text: str, is_private: bool, purpose: str = PURPOSE
) -> str | None:
    """Вычистить одну расшифровку. `None` — если модель не дала пригодного текста.

    По одной записи, а не пачкой, намеренно: чистка нужна **сейчас**, пока
    владелец смотрит в телефон, и ждать, пока наберётся пачка, значит показать
    ему дословный вариант. Замер поэтому тоже идёт по одной — иначе он мерил бы
    не тот режим, в котором работает воркер.

    `is_private` едет рядом с текстом, а не выясняется внутри: тот, кто
    собирается отправить текст наружу, обязан узнать про приватность из того же
    места, откуда взял текст (см. `ports.EntryText`). Дверь `core/llm` проверит
    это второй раз и поднимет исключение — но полагаться на вторую проверку
    вместо первой значит однажды остаться без обеих.

    `purpose` перебивается ровно одним местом — замером `just eval-cleanup`.
    Прогон по всему архиву это семьдесят вызовов за раз, и, попади они
    в `llm_calls` под меткой рабочей чистки, вопрос «сколько стоит чистка»
    получил бы ответ в десять раз больше правды. Ради этого вопроса таблица
    и заведена, поэтому метка у замера своя — как у прогона разметки.
    """
    completion = await llm.complete_over_entries(
        model,
        entries=[EntryText(entry_id=entry_id, text=text, is_private=is_private)],
        system=PROMPT,
        schema=response_schema(),
        temperature=TEMPERATURE,
        purpose=purpose,
    )
    return parse(completion.data, entry_id=entry_id)
