"""Что отключается первым, когда запросов к модели остаётся мало.

20 августа 2026 кончившаяся квота положила воркер вместе с расшифровкой
и напоминаниями (ADR-0014). Правило с тех пор явное и записано в ADR-0015,
пункт 6:

    не трогается никогда    приём, расшифровка, напоминания, разметка
    отключается первым      косметика: чистка и лид сводки

Признак — **наблюдённый отказ, а не настроенный лимит.** Суточный лимит
текстовой модели неизвестен, и `ENRICH_DAILY_QUOTA` пуст намеренно: число
из головы в `/status` читалось бы как измеренное. Механизм, который ждёт
настроенного числа, при пустой настройке не сработал бы ни разу — то есть
выглядел бы работающим и молчал ровно в тот день, ради которого написан.
Ждать заполнения настройки нельзя ещё и потому, что запросов после этой волны
станет вдвое больше.

Окно берётся из `core/quota`: сутки у провайдера тихоокеанские, и счёт
по полуночи владельца ошибался бы на девять часов.
"""

import logging
from datetime import datetime

from brain.core import quota
from brain.core.present import repository

logger = logging.getLogger(__name__)

# Код, по которому провайдер говорит «запросов больше нет». Он же приходит
# при слишком частых обращениях, и разделять эти два случая нечем — но для
# придерживания косметики разницы и нет: в обоих случаях лишний запрос сейчас
# отнимает место у расшифровки и напоминаний.
QUOTA_EXHAUSTED = 429


async def cosmetic_allowed(now: datetime) -> bool:
    """Можно ли тратить запрос на косметику.

    `False` означает «сегодня уже упирались»: в текущих сутках провайдера
    есть отказ `429` от текстовой модели. Придерживание держится до сброса
    квоты и снимается само — руками ничего делать не надо.
    """
    refused = await repository.refused_since(quota.window_start(now), status_code=QUOTA_EXHAUSTED)

    if refused:
        logger.info(
            "косметика придержана до %s: сегодня уже был отказ по квоте",
            quota.resets_at(now).isoformat(timespec="minutes"),
        )
    return not refused
