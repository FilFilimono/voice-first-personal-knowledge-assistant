"""Запись целиком — то, во что проваливаются из любой цитаты.

**Заведено 7 сентября 2026 решением владельца.** `vision.md` §8 требует прямым
текстом: «синтез плюс источники с датами, **всегда можно провалиться
в оригинал**». До этого дня выполнялась половина требования — дата у цитаты
была, а прочитать запись было нельзя ничем: длинная обрезалась, и команды
показать её в проекте не существовало вовсе.

Довод владельца дословно: *обрезка на 220 символах это то же «и ещё 64», только
в другом месте.* Претензия та же самая, что закрыла счётчик в утреннем
сообщении: за многоточием лежит то, что владелец забыл и достать не может.

**Форма — тапабельная команда, и она выбрана, а не досталась по умолчанию.**
`/e42` Telegram превращает в ссылку сам, потому что это `/слово` из латиницы
и цифр: один тап, набирать нечего. Кнопкой это не сделано намеренно — под
выдачей из пяти цитат нужно пять кнопок, а взаимодействовать с кнопками
владелец не хочет вовсе (приёмка Волны 1). Командой с датой — тоже нет:
за один день записей бывает несколько, и она неоднозначна.

**Якорь ставится в шести местах, а не в одном.** Цитата показывается в связях,
в раскачке, в разговоре по теме, в поиске, во всплывании и в напоминании
привычки. Механизм, работающий в четырёх местах из шести, в этом проекте уже
был — напоминания, работавшие только для текста, — и стоил двух недель.
Поэтому приставка и сборка якоря живут здесь, в одном месте, а не повторяются
строкой в каждом отправителе.

**Приватные записи показываются.** Это переписка владельца с собственным ботом,
наружу ничего не уходит — то же правило и та же причина, что у всплывания
(`vision.md` §5.3). Инвариант 5 про внешние сервисы, а не про то, что бот
показывает хозяину. Замочек при этом обязателен: владелец должен видеть,
с чем имеет дело.
"""

from dataclasses import dataclass
from datetime import datetime
from zoneinfo import ZoneInfo

from sqlalchemy import select

from brain.core.memory.repository import display_text, is_private_now
from brain.storage.db import session_scope
from brain.storage.models.entry import Entry

# Приставка якоря. Одна буква, потому что якорь стоит в конце **каждой** цитаты
# и любой лишний символ там платится шириной строки на телефоне. Латиница
# и цифры обязательны: `/запись42` Telegram ссылкой не сделает, и якорь
# пришлось бы набирать руками — то есть он перестал бы работать.
PREFIX = "e"

# Предел одного сообщения Telegram. Запись длиннее уезжает несколькими —
# **не обрезается**: обрезка здесь была бы возвращением ровно того дефекта,
# ради которого команда и заведена, только с большим числом.
MESSAGE_LIMIT = 4000

NOT_FOUND = "Не нашёл такой записи. Возможно, номер из очень старого сообщения."


def anchor(entry_id: int) -> str:
    """Якорь, которым цитата отсылает к оригиналу.

    Собирается здесь, а не строкой в каждом отправителе: шесть мест показывают
    цитату, и разъехавшаяся приставка сломала бы часть из них молча.
    """
    return f"/{PREFIX}{entry_id}"


@dataclass(frozen=True, slots=True)
class Shown:
    """Запись так, как её читает владелец."""

    entry_id: int
    # Вычищенный текст (`display_text()`), как везде в показе (ADR-0015, ось 3).
    # Дословный лежит рядом и не меняется, но показывать его здесь незачем:
    # владелец проваливается в оригинал, чтобы прочитать мысль, а не чтобы
    # сверить расшифровку.
    text: str
    created_at: datetime
    timezone: str
    # Спрашивается **сейчас** (`is_private_now`), а не колонкой: приватность
    # включают задним числом, и `entries` на UPDATE закрыта (инвариант 3).
    is_private: bool


async def full(entry_id: int) -> Shown | None:
    """Запись целиком. `None` — такой записи нет."""
    async with session_scope() as session:
        row = (
            await session.execute(
                select(
                    Entry.id,
                    display_text(),
                    Entry.created_at,
                    Entry.timezone,
                    is_private_now(),
                ).where(Entry.id == entry_id)
            )
        ).first()

    if row is None or row[1] is None:
        # Записи нет — либо номер из чужого сообщения, либо голосовое, которое
        # ещё не расшифровано. Второе тоже честнее назвать «нечего показать»,
        # чем показать пустоту.
        return None

    return Shown(
        entry_id=int(row[0]),
        text=str(row[1]),
        created_at=row[2],
        timezone=str(row[3]),
        is_private=bool(row[4]),
    )


def text(shown: Shown, *, now: datetime) -> str:
    """Запись словами. Без обрезки — в этом всё дело.

    `now` приходит параметром, а не берётся часами: год у даты пишется только
    у прошлогодней записи, и это решение зависит от «сегодня». Функция,
    смотрящая на часы сама, проверяется только тестом с прибитой датой, а такой
    тест зелен ровно до того дня, когда часы его обгонят — правило проекта,
    купленное тремя случаями за неделю.
    """
    when = shown.created_at.astimezone(ZoneInfo(shown.timezone))
    stamp = f"{when:%d.%m}" if when.year == now.year else f"{when:%d.%m.%Y}"
    lock = "🔒 " if shown.is_private else ""
    return f"📄 {lock}{stamp}, {when:%H:%M}\n\n{shown.text}"


def parts(said: str) -> list[str]:
    """Разбить длинный текст на сообщения по границе слова.

    Больше одного сообщения — обычный исход для длинного голосового, а не сбой.
    Режется по пробелу: обрубок посреди слова читается как ошибка, а склеенные
    обратно части обязаны давать те же слова — это и проверяется тестом.
    """
    said = said.strip()
    if len(said) <= MESSAGE_LIMIT:
        return [said]

    chunks: list[str] = []
    rest = said
    while len(rest) > MESSAGE_LIMIT:
        head = rest[:MESSAGE_LIMIT]
        cut = head.rfind(" ")
        # Слова длиннее предела не бывает у речи, но резать посередине лучше,
        # чем зациклиться: `cut == -1` означал бы бесконечный цикл.
        cut = cut if cut > 0 else MESSAGE_LIMIT
        chunks.append(rest[:cut].rstrip())
        rest = rest[cut:].lstrip()
    if rest:
        chunks.append(rest)
    return chunks
