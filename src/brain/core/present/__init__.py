"""Слой представления: модель пишет текст, который читает владелец.

Заведён ADR-0015 после недели ежедневного использования. Ревизия нашла одну
общую причину у всех жалоб сразу: **система извлекает, но нигде не
формулирует.** Всё, что видел владелец, — куски его собственной речи,
нарезанные по счётчику символов. Ни одна строка не была написана для него.

Граница слоя: он пишет текст, который увидит человек, и не делает больше
ничего. Отбор данных, пороги, бюджет касаний, расписание, порядок и нумерация
остаются кодом — принцип 12 («не звать модель там, где хватает кода») этим
решением не отменяется ни на сколько. Модель делает ровно то, чего код
не умеет: **пишет по-русски**.

Наружу ходим через существующую дверь `core/llm`, поэтому инвариант 5, учёт
в `llm_calls` и маршрутизация тира достаются конструкцией, а не повторяются.

Что здесь лежит:

    cleanup.py     чистка расшифровки: промпт, схема ответа, разбор
    titles.py      названия дел и петель: пачка, проверка, запись
    digest.py      лид утренней сводки: вход модели, промпт, отказ
    guard.py       проверка написанного моделью перед показом
    pacing.py      что замолкает первым, когда квота на исходе
    repository.py  чтение из базы, которое для этого нужно
"""

