"""Утренняя сводка: что сегодня висит.

`vision.md` §5.1: календарь на сегодня → незакрытые обещания → **одна** открытая
петля.

**Первая строка появилась 7 сентября 2026, вместе с Фазой 5.** До неё её
не было вовсе — не заглушкой, а отсутствием, — и это была самая заметная дыра
сводки: из всего, что делает фаза, владелец видит эту строку чаще всего,
каждое утро. Правила у неё три, и каждое проверяется тестом:

- встречи берутся за **сегодняшний день владельца**, а не за сутки UTC;
- **календарь поводом отправить сводку не является** (см. `Morning.empty`);
- **отказ календаря сводку не роняет** — она уйдёт без первой строки, ровно
  как уходила до фазы. Заглушки «календарь недоступен» нет намеренно.

**Почему сводка не подпадает под запрет ретроспективного упрёка**, хотя
и перечисляет несделанное. Она отдаёт день вперёд — «вот что сегодня висит», —
а не подводит итог прошедшему. Разница не в списке, а в том, к какому времени
он относится (`vision.md` §5.1, §7.0).

**Вчерашнего неразобранного здесь больше нет, и это решение владельца.** Строка
«Со вчера ждут разбора: N» держалась настоящим временем — «ждут», а не «ты
не разобрал», — и неделя использования показала, что защита не работает:
читается всё равно счёт несделанного, то есть ровно тот ретроспективный упрёк,
который §7.0 п.2 запрещает, и в том единственном сообщении, которое обязано
давать, а не требовать. Поля под неразобранное здесь нет вовсе: поле, которое
некому показывать, — это приглашение показать его снова. Число не потеряно,
его видно в `/status` («Ждут разбора») — там его **спрашивают**, а не получают
без спроса, и это разные сообщения.

**Почему без вызова модели.** Содержание — три списка из базы. Модель добавила
бы связки, а взамен принесла бы недетерминированность в единственное сообщение,
которое приходит каждый день, и сделала бы его непроверяемым быстрым тестом
(ADR-0013, ось 4). Это открытый вопрос с назначенным сроком проверки: через две
недели использования владелец отвечает, читает ли он сводку.
"""

from dataclasses import dataclass
from datetime import datetime

from brain.core.digest import by_topic, event_context, loops
from brain.core.digest import commitments as commitment_store
from brain.core.digest.by_topic import Slice
from brain.core.digest.event_context import Agenda
from brain.core.present.digest import MAX_DEEDS
from brain.storage.models.commitment import Commitment
from brain.storage.models.loop import Loop

# Сколько дел показывать. «Читается за 40 секунд» из `vision.md` §5.1 —
# это обещание, и список на двадцать пунктов его нарушает молча. Показываются
# старейшие: эскалация вверх по важности, а не по частоте (§7).
#
# С Задачи 7 их три, а не пять, и число берётся из слоя представления: там оно
# стоит рядом с бюджетом сообщения, потому что это правило показа, а не отбора.
# Своё число здесь однажды разъехалось бы с бюджетом молча, и заметить это
# можно было бы только по длине сводки. Остальные дела — по кнопке «все дела».
COMMITMENTS_SHOWN = MAX_DEEDS


@dataclass(frozen=True, slots=True)
class Morning:
    """Содержание утренней сводки. Пустое — значит молчим."""

    commitments: list[Commitment]
    open_commitments: int
    loop: Loop | None
    # Срез по темам всего архива — то, что встало на место счётчика «и ещё 64».
    # `None` — тем меньше двух, срезом это не назвать (`digest/by_topic`).
    topics: Slice | None = None
    # Встречи сегодняшнего дня вместе с поясом, в котором их читают.
    # `None` — календаря сегодня нет: не настроен либо не ответил. Пустой
    # список событий и `None` при этом значат для показа одно и то же —
    # первой строки не будет, — но различать их в данных надо: «встреч нет»
    # и «календарь молчит» это разные новости для `/status`.
    agenda: Agenda | None = None

    @property
    def empty(self) -> bool:
        """Нечего дать — не отправляем ничего (`vision.md` §7.0, принцип 3).

        Неразобранное содержанием не считается и раньше: повтор по живому архиву
        19 августа 2026 нашёл сводку 17 августа, состоявшую целиком из строки
        «Со вчера ждут разбора: 2», и после него неразобранное перестало быть
        поводом отправить сводку. Теперь оно не попадает в неё вовсе — см.
        шапку модуля, — и это условие осталось тем же самым: дела и петля.

        **Срез по темам поводом отправить сводку не является, и это намеренно.**
        Он не меняется день ото дня — это оглавление архива, а не новость,
        — и сводка, состоящая из одного оглавления, была бы ежедневным
        сообщением ни о чём. Он приходит вместе с тем, что и так есть,
        и добавляет к нему доступ к архиву.

        **Календарь поводом отправить сводку не является по той же причине.**
        Сводка из одного расписания — это пересказ того, что владелец и так
        видит в календаре, и приходила бы она каждый рабочий день. Встречи
        едут первой строкой к тому, что и так есть, а не вместо него.
        """
        return not self.commitments and self.loop is None

    @property
    def loop_stuck(self) -> bool:
        """Петлю уже трижды откладывали — `vision.md` §5.2 велит сменить вопрос.

        Признак живёт здесь, а не у каждого читателя, потому что читателей два
        и они обязаны сказать одно и то же: текст сводки (`render.morning`)
        и кнопки под ней (через нагрузку касания в `service._prepare`).
        Посчитай его каждый сам — и разъехаться они смогут молча, а это ровно
        тот почерк, которым в проекте уже потерялась `loops.is_stuck`.
        """
        return self.loop is not None and loops.is_stuck(self.loop.times_asked)


async def collect(now: datetime, timezone: str | None = None) -> Morning:
    """Собрать сводку на сегодня. Ничего не отправляет и ничего не помечает.

    **Таймзона вернулась 7 сентября 2026, и вернулась по делу.** Она была
    убрана вместе с вчерашним неразобранным — единственным, ради чего тогда
    требовалась, — и убрана правильно: аргумент «на будущее» означал бы, что
    путь к убранной строке ещё цел. Теперь у неё снова есть работа: «сегодня»
    для календаря — это сутки владельца, а не сутки UTC.

    `None` означает «календарь не спрашиваем вовсе». Так сводку зовёт повтор
    по прошедшим дням архива (`evals/digest/replay`): чужих встреч в тех днях
    неоткуда взять, а ходить в сеть замеру незачем.
    """
    # Момент нужен и здесь: отложенное дело возвращается сроком, а не заданием,
    # и «что висит» — вопрос про сейчас, а не про состояние в базе.
    #
    # Показываемые дела и их общее число считаются **разными запросами**,
    # и с 6 сентября 2026 иначе нельзя: отбор больше не «верхушка списка»,
    # а ротация со свежестью темы (`commitments.for_morning`), и срезать
    # её из общего списка значило бы повторить порядок в двух местах.
    return Morning(
        commitments=await commitment_store.for_morning(now, COMMITMENTS_SHOWN),
        open_commitments=await commitment_store.open_count(now),
        loop=await loops.pick(now),
        # Срез по **всему** архиву, а не за неделю: он заменил счётчик «и ещё
        # 64», а за тем счётчиком лежало забытое, и лежало оно не в последней
        # неделе. Разбор — `by_topic.collect`.
        topics=await by_topic.collect(now, days=None),
        # Календарь — последним в сборке и первым в тексте. Последним потому,
        # что он единственный ходит в сеть, и его отказ не должен стоить
        # остальным трём запросам к базе; первым в тексте — решение владельца
        # от 07.09.2026, разобранное в `render.morning`.
        agenda=None if timezone is None else await event_context.agenda(now, timezone),
    )
