"""Как касания выглядят словами.

Текст живёт в ядре, а не в адаптере, — по образцу `core/enrich/reply.py`.
Граница проведена так: **что сказано** решает ядро, **чем это нажимается** —
адаптер. Ядро не знает, что кнопки бывают inline; адаптер не знает, почему
дела показываются старейшими.

Тон задан `vision.md` §7.0 и проверяется здесь построчно:

- **никаких счётчиков-достижений.** «Закрыл 4 дела» в ревью — это констатация
  за период, а не балл, и рядом с ней нет ни процента, ни серии;
- **никакого упрёка.** Проверка здесь не «как сформулировано», а «что прочтёт
  владелец»: строка «Со вчера ждут разбора: N» была написана в настоящем
  времени именно ради этого правила — и всё равно читалась как счёт
  несделанного, поэтому убрана из утренней сводки совсем (см. `morning`).
  Формулировка спасает не всегда; счётчик долга не спасает никогда.
"""

from collections.abc import Sequence
from datetime import datetime
from zoneinfo import ZoneInfo

from brain.config import get_settings
from brain.core.digest.evening import Disputed
from brain.core.digest.morning import Morning
from brain.core.digest.prompting import Question
from brain.core.digest.resurface import Old
from brain.core.digest.weekly import Weekly
from brain.core.enrich.reply import NAMES
from brain.core.present import entry as entry_view
from brain.core.present.guard import Written
from brain.core.retrieval.links import Link
from brain.core.scheduler import recurrence
from brain.storage.models.commitment import Commitment, CommitmentState
from brain.storage.models.habit import Habit

# Сколько символов записи показывать в списке. Больше — и сводка перестаёт
# читаться за сорок секунд, меньше — и по обрывку не узнать, о чём речь.
#
# С Задачи 4 это **запасной путь**, а не основной: у дела и петли есть
# написанное название (ADR-0015, п. 4), и обрезок показывается, только когда
# названия нет — модель не ответила, ответила не тем или её ответ отверг гвард.
# Удалять его нельзя никогда, ровно как сухой рендер сводки: он и есть
# та мягкая деградация, которой куплена недетерминированность.
SNIPPET = 70

# Возраст петли, после которого `vision.md` §6 велит читать его как перегрузку,
# а не как лень. Формулировка меняется вместе с числом — иначе цифра сама
# по себе прочитается как упрёк.
OVERLOADED_DAYS = 30


def snippet(text: str, limit: int = SNIPPET) -> str:
    """Кусок записи одной строкой."""
    flat = " ".join(text.split())
    if len(flat) <= limit:
        return flat
    return flat[: limit - 1].rstrip() + "…"


def morning(content: Morning, written: Written | None = None, asked: Question | None = None) -> str:
    """Утренняя сводка. Смотрит вперёд: «вот что сегодня висит».

    **Порядок переписан 6 сентября 2026, и переписан целиком, а не подправлен.**
    Владелец отверг прежнее сообщение дословно: «висит раз, два, три и ещё 64.
    Эти три я вижу каждое утро, они одинаковые. Самая ненужная херня, которая
    может быть». Три дефекта чинились по одному:

    | было | стало |
    |---|---|
    | те же три дела каждое утро | ротация со свежестью темы (`for_morning`) |
    | «…и ещё 64» — счётчик, запрещённый §7.0 п.5 | срез по темам с `/recall` |
    | материала из архива нет вовсе | связанное старое — первой строкой |

    Порядок сообщения теперь такой: **материал → срез по темам → дела →
    вопрос**. Это прямое требование владельца, и смысл его в том, что сверху
    стоит то, что можно **прочитать**, а не сделать: сообщение, начинающееся
    со списка долгов, на 100% состоит из того, что владелец должен, и на 0%
    из того, что он думал (`vision.md` §1.1 и §7.0, принцип 1).

    Материал и вопрос — **одна вещь, разложенная по двум концам сообщения**:
    факт из архива сверху, вопрос про него внизу. Собирает их раскачка
    (`digest/prompting`), а не этот модуль: здесь только место, куда они встают.

    `written` — то, что написала модель (ADR-0015, п. 5). `None` означает
    **сухой рендер**: тот же текст слово в слово, каким сводка была до Задачи 7.
    Он приходит, когда модель не ответила, когда её ответ отверг гвард, когда
    косметика придержана квотой — и он не удаляется никогда, потому что он
    и есть та защита, которой куплена недетерминированность в единственном
    сообщении, приходящем каждый день.

    Модель пишет **только лид**. Строки дел — это названия из базы, номера
    ставит код, вопрос под петлёй выбирает код: кнопка это действие, текст это
    речь, и вопрос, не совпадающий с кнопками, оставляет человека без
    понимания, что нажимать.

    **Кончается вопросом петли или списком дел, и приписки после них нет.**
    Здесь стояла строка «🤔 Со вчера ждут разбора: N. Покажу вечером.», и убрал
    её владелец после недели чтения: настоящее время («ждут», а не «ты
    не разобрал») задумывалось как защита от ретроспективного упрёка, а на
    экране всё равно читался счёт несделанного — в сообщении, которое обязано
    давать, а не требовать (`vision.md` §7.0, принципы 1 и 2).

    Возвращать её как «полезное напоминание» не надо: спорные записи владелец
    получает вечером и только тогда, когда есть что показать, а число ждущих
    разбора видно в `/status` по запросу.
    """
    lines = ["☀️ Утро."]

    # 1. Материал. Первым идёт то, что можно прочитать, а не сделать.
    lines += _material(asked)

    # 2. Срез по темам — доступ к архиву на месте бывшего счётчика.
    lines += _topics(content)

    # 3. Дела и петля. Лид пишет модель и он про дела, поэтому стоит перед
    # ними, а не под шапкой: над материалом из архива он читался бы ответом
    # не на тот вопрос.
    #
    # Порядок дел и петли — настройка, а не решение автора: `vision.md` §5.2
    # называет петлю ядром системы, но внизу сообщения её увидят последней,
    # а дела внизу — это список, до которого не дошли. Данных нет ни за одно
    # (ADR-0015, цена), поэтому выбирает наблюдение.
    blocks = [_deeds(content, written), _loop(content)]
    if get_settings().digest_order == "loop_first":
        blocks.reverse()

    for block in blocks:
        lines += block

    # 4. Вопрос — последним. Отвечают на него голосом, и ответ становится
    # записью архива (`digest/prompting.answered`).
    lines += _question(asked)

    return "\n".join(lines)


def _material(asked: Question | None) -> list[str]:
    """Материал из архива — старое, связанное с тем, о чём владелец говорит.

    Пусто — обычный исход, а не сбой, и это **прямое указание владельца**:
    «связного не нашлось — вид в этот день молчит, а не выдаёт случайное.
    Лучше промолчать, чем показать несвязанное». Прежнее всплывание давало
    случайную мысль без повода, и претензия была ровно об этом.
    """
    if asked is None or not asked.material:
        return []
    return ["", f"🔗 {asked.material}"]


def _topics(content: Morning) -> list[str]:
    """Срез по темам. То, что встало на место счётчика «…и ещё 64».

    **Разница между ними не в оформлении, а в том, что с этим можно сделать.**
    Счётчик сообщал число и не давал ничего: за ним лежали записи, о которых
    владелец забыл, и система не напомнила бы о них никогда. Срез называет
    темы, и каждая разворачивается в свои записи по `/recall` — то есть
    это дверь в архив, а не сообщение о его размере.

    Счётчиком по §7.0 п.5 это не является: запрещён счётчик **достижений
    и долгов** — сколько сделано, сколько пропущено, сколько висит. Число
    записей по теме не оценивает владельца и ничего от него не требует;
    оно говорит, сколько там лежит, если он захочет посмотреть.
    """
    if content.topics is None:
        return []
    listing = " · ".join(
        f"{_titled(topic.name)} {topic.entries}" for topic in content.topics.topics
    )
    return [
        "",
        f"📚 В архиве: {listing}",
        # Команда — строчными, как тема лежит в базе: она ищется по slug,
        # и владельцу не надо гадать про регистр. Но показанное имя и набранное
        # тогда различаются, и это осознанная цена: список читается глазами,
        # а команда набирается пальцем.
        f"Развернуть: /recall {content.topics.topics[0].name}",
    ]


def _titled(name: str) -> str:
    """Имя темы с заглавной. `str.capitalize` тут не годится.

    Он опускает остальные буквы, и «CV чек» превратился бы в «Cv чек».
    Имена тем приходят от модели и лежат в базе как есть — трогать их дальше
    первой буквы нельзя, это тот же запрет, что на правку услышанных имён.
    """
    return name[:1].upper() + name[1:]


def _deeds(content: Morning, written: Written | None = None) -> list[str]:
    """Список дел. Пустой, если их нет: заголовка без списка не бывает.

    **Строки «…и ещё N» здесь больше нет.** Она была счётчиком, запрещённым
    `vision.md` §7.0 п.5, и владелец назвал её главной болью сообщения:
    за многоточием лежали дела, о которых он забыл, и достать их было нельзя.
    Заменена срезом по темам — см. `_topics`.

    Число открытых дел не потеряно: его видно в `/status`, где его
    **спрашивают**, а не получают без спроса. Это разные сообщения.
    """
    if not content.commitments:
        return []

    lines = []
    if written is not None:
        lines += ["", written.lead]

    # Дела нумеруются, потому что закрываются кнопками, а текст дела в подпись
    # кнопки не помещается: на телефоне это два-три слова. Номер — единственный
    # способ связать кнопку с делом, не обрезая его до неузнаваемости.
    lines += ["", "Висит:"]
    lines += [
        f"{number}. {snippet(item.title or item.text)}{_started(item)}"
        for number, item in enumerate(content.commitments, start=1)
    ]
    return lines


def _question(asked: Question | None) -> list[str]:
    """Вопрос раскачки — последней строкой сообщения.

    Отбит пустой строкой и своим значком: он единственное место сообщения,
    которое чего-то ждёт, и смешать его с делами значит потерять и то,
    и другое.
    """
    return [] if asked is None else ["", f"💬 {asked.text}"]


def _loop(content: Morning) -> list[str]:
    """Петля и вопрос под ней. Оба — код, и после Задачи 7 тоже: см. `morning`."""
    if content.loop is None:
        return []
    return [
        "",
        f"🔁 Ты хотел разобраться: {snippet(content.loop.title or content.loop.question)}",
        _asking(content),
    ]


def _started(item: Commitment) -> str:
    """Пометка «в работе» — значок в конце строки, а не отдельный раздел.

    Раздел означал бы два списка вместо одного, а сводка обязана читаться
    за сорок секунд (`vision.md` §5.1). Значок именно песочные часы: `▸`
    на телефоне бледный и читается как маркер списка, то есть не значит ничего.
    """
    return " ⏳" if item.state is CommitmentState.IN_PROGRESS else ""


def _asking(content: Morning) -> str:
    """Что спрашивается под петлёй. Признак приходит готовым — см. `Morning`.

    Две причины, по которым вопрос меняется после третьего откладывания.

    Первая: кнопки под петлёй в этот момент уже другие — «Закрыть ·
    Переформулирую», без «ещё думаю» (`vision.md` §5.2). Текст и кнопки,
    спрашивающие разное, — это расхождение, и вылезло бы оно в худшем месте:
    сухой рендер по ADR-0015 показывается ровно тогда, когда гвард отбраковал
    ответ модели, то есть он постоянный запасной путь, а не заглушка.

    Вторая и важнее: «Сдвинулось?» на трижды отложенной петле — вопрос,
    на который владелец уже трижды ответил «ещё думаю». Спросить его четвёртый
    раз значит мягко упрекнуть за прошедшее, а сообщение даёт, а не требует
    (`vision.md` §7.0, принцип 1).
    """
    return "Закрыть или переформулируешь?" if content.loop_stuck else "Сдвинулось?"


def evening(items: list[Disputed]) -> str:
    """Вечерний разбор: спорные записи пачкой.

    Приходит только когда есть что показать, поэтому пустого варианта здесь нет
    вовсе — и это не упущение, а то самое «вечер приходит только с отдачей».
    """
    lines = ["🤔 Тут я не уверен. Подскажете?", ""]
    for number, item in enumerate(items, start=1):
        lines.append(f"{number}. {snippet(item.text)}")
        lines.append(f"   {_guess(item)}")
    return "\n".join(lines)


def _guess(item: Disputed) -> str:
    """Чем система считает запись и в чём именно сомневается."""
    if item.alternative_type is not None:
        return f"{NAMES[item.type]} или {NAMES[item.alternative_type]}?"
    return f"похоже на «{NAMES[item.type]}», но уверенности нет"


def habit(item: Habit, said: Sequence[Link] = (), *, timezone: str) -> str:
    """Напоминание привычки. Даёт повод рассказать, а не требует отчёта.

    Три правила `vision.md` §5.11 держатся здесь построчно, и каждое из них
    легко нарушить, ничего не заметив.

    **Несёт контекст, а не одно название.** Голое «почитай книгу» — будильник,
    а от будильника отписываются. Поэтому вместе с напоминанием показывается
    то, что владелец **сам говорил по этой теме**: связанные записи, считанные
    векторной близостью (`vision.md` §5.4, инвариант 8). Связей нет — обычный
    исход, а не сбой: тогда остаётся ритм и вопрос, и это всё ещё не будильник,
    потому что вопрос открытый.

    **Вопрос про ход, а не про факт.** Не «сделал или нет»: это счётчик,
    запрещённый §7.0 п.5, и отвечают на него кнопкой, а не словами.
    Спрашивается продвижение — и отвечается голосом, то есть новой записью.

    **Вчерашнего здесь нет ни в каком виде.** Ни «пропустил», ни «третий день»,
    ни сколько раз спрашивали: не выполненная вчера привычка не долг, она
    просто наступает снова (§5.11 и §7.0, принципы 2 и 5). Данных для такой
    строки в таблице нет по построению — но написать её можно и из `created_at`,
    и это стоит помнить при любой правке.
    """
    lines = [f"🌱 {recurrence.NAMES[item.rhythm].capitalize()}: {snippet(item.text, limit=120)}"]

    for link in said:
        when = link.created_at.astimezone(ZoneInfo(timezone))
        lines += [
            "",
            f"Ты говорил об этом {when:%d.%m}:",
            f"«{snippet(link.text, limit=200)}»  {entry_view.anchor(link.entry_id)}",
        ]

    lines += ["", HABIT_QUESTION]
    return "\n".join(lines)


# Вопрос под привычкой. Открытый и про движение: «сделал?» отвечается одним
# словом и ничего не оставляет в архиве, а «что мешает» вытаскивает мысль —
# ровно то, ради чего привычка и заведена отдельным типом (`vision.md` §5.11,
# последний абзац: привычка — носитель раскачки).
#
# Шаблон кода, а не текст модели. Полный режим (`vision.md`, план Фазы 4)
# отдаёт этот вопрос модели, и ветка под него пишется вместе с настройкой,
# которой сейчас нет, — см. отчёт блока B.
HABIT_QUESTION = "Как продвижение? Что получается, что мешает?"


def resurfaced(old: Old, *, timezone: str) -> str:
    """Всплывшая запись. Без повода и без вопроса — на то и всплывание."""
    when = old.created_at.astimezone(ZoneInfo(timezone))
    body = snippet(old.text, limit=400)
    return f"📄 Из архива, {when:%d.%m.%Y}:\n\n{body}\n\n{entry_view.anchor(old.entry_id)}"


def weekly(review: Weekly) -> str:
    """Недельное ревью — сведённые данные, а не рассказ.

    Рассказ придёт в Фазе 6 вместе с дорогим тиром; притворяться им сейчас
    значило бы выдать список за то, по чему `vision.md` §1.1 судит проект.
    """
    lines = ["🗓 Неделя.", ""]

    voiced = f", из них голосом {review.voice}" if review.voice else ""
    lines.append(f"Записей: {review.entries}{voiced}.")

    if review.topics:
        named = ", ".join(f"{name} ({count})" for name, count in review.topics[:5])
        lines.append(f"О чём: {named}.")

    if review.done:
        lines.append(f"Закрыл: {len(review.done)}.")
    if review.dropped:
        lines.append(f"Убрал как неактуальное: {len(review.dropped)}.")

    hanging = _hanging(review)
    if hanging:
        lines.append(hanging)

    if review.hint:
        lines += ["", f"💡 {review.hint}"]

    return "\n".join(lines)


def _hanging(review: Weekly) -> str:
    """Что осталось висеть — и как это читать, если висит давно."""
    parts = []
    if review.open_commitments:
        parts.append(f"дел {review.open_commitments}")
    if review.open_loops:
        parts.append(f"открытых вопросов {review.open_loops}")
    if not parts:
        return ""

    line = f"Висит: {', '.join(parts)}."
    if review.oldest_loop_days is not None and review.oldest_loop_days > OVERLOADED_DAYS:
        # Формулировка из `vision.md` §6: старая петля — признак перегрузки,
        # а не лени, и сказать это вслух дешевле, чем дать цифре прочитаться
        # самой.
        line += f" Старейший вопрос висит {review.oldest_loop_days} дней — это перегрузка."
    return line


def local(moment: datetime, timezone: str) -> datetime:
    """Момент в таймзоне владельца — для дат в тексте."""
    return moment.astimezone(ZoneInfo(timezone))
