"""Касания: когда система говорит сама, а когда молчит.

Фаза 4. До неё система только отвечала — на запись, на команду, на напоминание,
которое владелец сам поставил. Разница не количественная: реактивное сообщение
владелец вызвал, инициативное он получает, когда занят чем-то другим, и оно
либо оправдывает вторжение, либо приучает не открывать бота.

Правила, по которым это устроено, — `vision.md` §7.0, решение — ADR-0013.
Два из них определяют устройство всего модуля:

- **нечего дать — молчим, но молчание записывается.** Без строки в журнале
  тишина системы неотличима от её смерти, а именно так пряталась каждая
  из восьми дыр Фаз 1–2;
- **сообщение даёт, а не требует.** Отсюда вечер, который не приходит без
  спорных записей, и долг, который фиксируется молча.

Ни один механизм здесь не зовёт модель. Содержание сводки — три списка
из базы, и код с ними справляется; вызов добавил бы связки, а взамен принёс
недетерминированность в единственное сообщение, приходящее каждый день
(ADR-0013, ось 4). Это открытый вопрос с назначенным сроком проверки,
а не закрытое решение — `vision.md` §5.1.

Что где лежит:

    by_topic.py     срез по темам за период и «вспомним подробно»
    slots.py        чистая арифметика времени: чей момент наступил
    touches.py      журнал касаний и бюджет
    quiet.py        пауза и «сегодня выходной»
    commitments.py  дела: заведение из единиц разметки и закрытие
    habits.py       привычки: свой ритм напоминаний, вне бюджета и беззвучно
    loops.py        открытые петли — ядро системы по `vision.md` §5.2
    resurface.py    всплывание старого
    evening.py      спорные записи и долг, который не копится
    weekly.py       недельное ревью, включающееся по данным
    morning.py      сборка утренней сводки
    service.py      тик: что из этого сегодня уместно
"""

