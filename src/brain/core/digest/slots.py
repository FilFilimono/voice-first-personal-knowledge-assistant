"""Когда наступает момент касания. Чистая арифметика времени, без базы.

Вынесено отдельно затем, чтобы проверяться быстрым тестом: ошибка здесь
не падает, а сдвигает сообщения на час — и обнаруживается через месяц,
по ощущению.

**Почему у каждого слота окно, а не только час начала.** Воркер может лежать
полдня. Без окна поднявшийся в полночь процесс высыпал бы разом всё, что
не отправил, — четыре сообщения подряд ночью. Хуже того, утренняя сводка про
сегодняшний день, присланная в 23:00, перестаёт быть сводкой про сегодняшний
день и становится отчётом о прошедшем, то есть ровно тем сообщением, которое
запрещено принципом 2 (`vision.md` §7.0).

**Пропущенное окно не оставляет следа в журнале намеренно.** Отсутствие строки
означает «мы даже не дошли до решения» — это другое, чем «решили промолчать»,
и `/status` должен уметь их различать: первое значит, что воркер лежал,
второе — что всё в порядке.
"""

from datetime import date, datetime
from zoneinfo import ZoneInfo

from brain.storage.models.touch import TouchSlot

# Час открытия и час закрытия окна, в таймзоне владельца. Верхняя граница
# исключающая: `[open, close)`.
#
# Утро — единственный якорь дня (`vision.md` §7.0, принцип 4), поэтому 09:00
# записано в замысле и не выбирается. Полдень как граница: после него сводка
# «вот что сегодня висит» уже не опережает день, а догоняет его.
#
# Остальные три часа выбраны, а не измерены, и это надо знать: данных о том,
# когда владелец читает бота, пока нет вовсе. Первый способ их получить —
# две недели использования, они же критерий закрытия фазы.
WINDOWS: dict[TouchSlot, tuple[int, int]] = {
    TouchSlot.MORNING: (9, 12),
    TouchSlot.DAY: (13, 19),
    TouchSlot.WEEKLY: (20, 24),
    TouchSlot.EVENING: (21, 24),
}

# Воскресенье. `weekday()` считает от понедельника-нуля.
SUNDAY = 6


def local(now: datetime, timezone: str) -> datetime:
    """Тот же момент в таймзоне владельца."""
    return now.astimezone(ZoneInfo(timezone))


def local_date(now: datetime, timezone: str) -> date:
    """Сутки владельца, а не сервера.

    По ним считается бюджет касаний и уникальность слота в сутки. Разница
    не теоретическая: в 00:30 по Риму в UTC ещё вчера, и бюджет, посчитанный
    по UTC, разрешил бы лишнее касание за один вечер.
    """
    return local(now, timezone).date()


def due(now: datetime, timezone: str) -> list[TouchSlot]:
    """Слоты, чей момент наступил и ещё не прошёл. В порядке отправки.

    Порядок хронологический — по часу открытия окна. Воркер, поднявшийся
    вечером воскресенья, отправит ревью раньше разбора, и это читается как
    вечер, а не как случайная стопка сообщений.
    """
    moment = local(now, timezone)
    ready = [
        slot
        for slot, (opens, closes) in WINDOWS.items()
        if opens <= moment.hour < closes and _right_day(slot, moment)
    ]
    return sorted(ready, key=lambda slot: WINDOWS[slot][0])


def _right_day(slot: TouchSlot, moment: datetime) -> bool:
    """Недельное ревью бывает только в воскресенье. Остальные — каждый день."""
    if slot is TouchSlot.WEEKLY:
        return moment.weekday() == SUNDAY
    return True
