"""Что именно спрашивают у модели и в каком виде она обязана ответить.

Файл отделён от `service.py` намеренно: промпт — это то, что меняется чаще
всего и от чего зависит замер. Лежащий отдельно, он виден целиком и правится
не задевая логики.

**Примеров в промпте нет, и это не забывчивость.** Few-shot из архива был бы
здесь уместнее всего — но примеры пришлось бы держать в коде, то есть в git,
а архив в git не уходит ([ADR-0002](../../../../docs/adr/0002-privacy.md)).
Выбор между «промпт получше» и «архив в публичной истории» решается в одну
сторону. Если few-shot понадобится, примеры будут подниматься из базы
в рантайме — из подтверждённых кнопкой «не туда» разборов.

**Определения типов — русские, значения enum'а английские.** Таблицы перевода
между ними нет: модель возвращает ровно то, что ложится в колонку. Таблица
однажды разъехалась бы с одной из сторон, и заметить это можно было бы только
по странной статистике (ADR-0011).
"""

from collections.abc import Sequence
from typing import Any

from brain.storage.models.annotation import AnnotationType

# Определения. Каждое — про признак, по которому тип отличается от соседнего,
# а не про то, как он называется: «мысль» и «понимание» модель различает плохо,
# если не сказать, чем именно они различаются.
DEFINITIONS: dict[AnnotationType, str] = {
    AnnotationType.THOUGHT: (
        "рассуждение, идея, наблюдение. Ничего не решено и никто ничего не должен"
    ),
    AnnotationType.TASK: "то, что человек собирается сделать сам",
    AnnotationType.EVENT: (
        "то, что произойдёт в известное время и произойдёт независимо от него: "
        "экзамен, встреча, матч"
    ),
    AnnotationType.LOOP: "вопрос, который он задал себе и не додумал; хочет вернуться",
    AnnotationType.DECISION: "выбор уже сделан, назван ожидаемый исход",
    AnnotationType.ERROR: "что-то пошло не так, и он это разбирает",
    AnnotationType.INSIGHT: "«понял, что...» — новое понимание, а не план",
    AnnotationType.REFUSAL: "решил чего-то НЕ делать",
    AnnotationType.NOISE: (
        "смысла в записи нет: проверка бота, обрывок, случайное нажатие, "
        "ответ на вопрос бота вроде «в 14:50»"
    ),
}

# Граница, которую пришлось провести отдельной строкой. Замер 19.08.2026:
# при трёх прогонах все напоминания разом уезжали между «задача» и «событие»,
# а это половина архива. Без явного правила вечерний разбор получал бы
# четырнадцать записей за раз, и не потому, что они спорные.
TASK_VERSUS_EVENT = (
    "Просьба «напомни мне сделать X» — это task: напоминание про собственное "
    "действие. Event — только то, что случится само: экзамен, встреча, матч. "
    "«Напомни уйти домой в 19:40» — task. «Во вторник в 9:00 у меня экзамен» — event."
)

# Правило про темы переписано 19.08.2026 после прогона по живому архиву.
# Первая редакция запрещала процессные темы одной фразой — и модель завела
# «планирование», приписала его девяти записям и **приложила обоснование**
# («нет тем для организации времени и проверки календаря»). Запрет, на который
# ссылаются в обход, — это не запрет, а пожелание.
#
# Что изменилось: у записи может не быть темы вовсе. Раньше такой возможности
# в инструкции не было, и модель, обязанная назвать хоть что-то, честно
# изобретала процессную тему для «напомни уйти домой в 19:40» — у которой темы
# и правда нет.
TOPIC_RULES = (
    "Темы — о чём запись по существу: предмет, проект, человек, область. "
    "То, что система с записью делает, темой не бывает никогда: "
    "«напоминание», «планирование», «организация времени», «заметка», "
    "«тестирование» — не темы.\n"
    "**У записи может не быть темы.** У «напомни уйти домой в 19:40» темы нет: "
    "это действие, а не предмет. Пустой список тем — правильный ответ, и он "
    "лучше выдуманной темы.\n"
    "Но у мысли, понимания, решения и открытого вопроса предмет почти всегда "
    "есть — назови его. Пустой список там, где запись про действие или "
    "служебная.\n"
    "Ниже дан список уже заведённых тем. **Попади в него, если тема подходит "
    "по существу** — тогда напиши имя ровно так, как оно дано. Если не "
    "подходит ни одна, это нормально: заводи свою, коротким словосочетанием "
    "в именительном падеже, нижним регистром, и заполни new_topic_reason. "
    "Натягивать запись на далёкую тему из списка хуже, чем завести новую: "
    "тема, в которую сложили всё подряд, перестаёт что-либо значить."
)

NO_TOPICS_YET = "(тем ещё нет — все темы будут новыми)"

# Правило нарезки. Границы предлагает модель, а не код: замер 19.08.2026
# показал, что предложение не всегда достаточная граница. Запись 15 целиком —
# «по итогу я перенес Cv чек на завтра в 16:00 , сейчас надо к нему полностью
# подготовится»: решение и задача через запятую, точки между ними нет, потому
# что расшифровка знаков не ставит. Оба прогона пытались разрезать это
# предложение надвое и упирались в запрет (ADR-0012).
#
# Граница выражается **цитатой начала**, а не номером символа: считать символы
# модели не умеют, а цитату можно найти в тексте и проверить. Цитата короткая
# намеренно — выход это 89% стоимости разметки, и просить пересказ всей единицы
# значило бы платить за копию архива в каждом ответе.
UNIT_RULES = (
    "Запись может содержать несколько разных вещей сразу: подумал вслух, "
    "решил, надо не забыть. Разбей её на смысловые единицы — куски, идущие "
    "подряд, у каждого свой тип.\n"
    "**Одна единица на всю запись — частый и правильный ответ.** Дели только "
    "там, где человек действительно переключился с одного на другое. "
    "Не дроби мысль на предложения: три предложения об одном — это одна "
    "единица.\n"
    "Границу можно ставить и внутри предложения: живая речь идёт без знаков "
    "препинания, и «перенёс встречу на завтра, надо подготовиться» — это "
    "решение и задача в одном предложении.\n"
    "Каждая единица описывается началом: `start` — первые три-пять слов "
    "единицы, выписанные **дословно из текста записи**, вместе с опечатками "
    "расшифровки. У первой единицы это начало записи. Единицы идут подряд "
    "и покрывают запись целиком."
)


def build_system(topic_names: Sequence[str]) -> str:
    """Системная часть запроса: правила и список тем, который уже есть."""
    types = "\n".join(f"- {member.value} — {DEFINITIONS[member]}" for member in AnnotationType)
    topics = "\n".join(f"- {name}" for name in topic_names) if topic_names else NO_TOPICS_YET

    return f"""Ты размечаешь личный архив мыслей одного человека. Записи надиктованы
голосом или набраны на ходу: они бывают оборванными, с ошибками расшифровки
и без знаков препинания. Разбирай то, что человек имел в виду, а не то, как
это записалось.

{UNIT_RULES}

Тип единицы — ровно один из девяти:
{types}

{TASK_VERSUS_EVENT}

{TOPIC_RULES}

Уже заведённые темы:
{topics}

Темы и сущности — у записи целиком, а не у каждой единицы. Сущности — имена
собственные, продукты и люди, названные в записи, выписанные так же,
как в тексте.

Ответь на каждую запись ровно один раз, с тем же id, в том же порядке."""


def response_schema() -> dict[str, Any]:
    """Схема ответа. Провайдер держит её сам — это не просьба, а ограничение.

    Полей ровно столько, сколько нужно: восемьдесят девять процентов стоимости
    разметки — выход, поэтому лишнее поле здесь дороже лишнего абзаца выше.

    Необязательных значений вида пустой строки в enum'е быть не может —
    провайдер отклоняет такую схему целиком (`400 enum[N]: cannot be empty`).
    «Значения нет» здесь означает отсутствие поля.
    """
    return {
        "type": "object",
        "properties": {
            "items": {
                "type": "array",
                "items": {
                    "type": "object",
                    "properties": {
                        "id": {"type": "integer"},
                        # Единиц почти всегда одна. Потолок нужен ровно затем,
                        # чтобы запись не рассыпалась на предложения: восемь
                        # смысловых переключений в одном голосовом не бывает,
                        # а вот восемь предложений — сплошь и рядом.
                        "units": {
                            "type": "array",
                            "minItems": 1,
                            "maxItems": 8,
                            "items": {
                                "type": "object",
                                "properties": {
                                    "start": {"type": "string"},
                                    "type": {
                                        "type": "string",
                                        "enum": [member.value for member in AnnotationType],
                                    },
                                },
                                "required": ["start", "type"],
                            },
                        },
                        "topics": {
                            "type": "array",
                            "items": {"type": "string"},
                            "maxItems": 3,
                        },
                        "new_topic_reason": {"type": "string"},
                        "entities": {"type": "array", "items": {"type": "string"}},
                    },
                    "required": ["id", "units", "topics", "entities"],
                },
            }
        },
        "required": ["items"],
    }
