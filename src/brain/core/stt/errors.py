"""Ошибки расшифровки.

Отдельным модулем, чтобы провайдер мог их поднимать, не импортируя пакет,
который сам же его и собирает. Побочная польза — по этому файлу видно все
способы, которыми расшифровка может не получиться.
"""


class PrivateContentError(RuntimeError):
    """Попытка отправить приватную запись во внешний сервис.

    Не «ошибка пользователя», а сработавший предохранитель: если это исключение
    поднялось, где-то в коде потерялась проверка режима до приёма записи.
    Повторять такое задание бессмысленно — оно упадёт так же.
    """


class AudioTooLongError(RuntimeError):
    """Голосовое длиннее потолка из ADR-0007. Повтор не поможет."""


class TranscriptionError(RuntimeError):
    """Провайдер не ответил или ответил непонятным. Задание будет повторено."""
