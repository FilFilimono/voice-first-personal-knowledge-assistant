"""Стык очереди с сессией SQLAlchemy.

Приложение пишет через SQLAlchemy, а pgqueuer умеет говорить только с сырым
соединением asyncpg. Если взять для очереди отдельное соединение, обе вставки
уедут в разные транзакции и инвариант 7 развалится молча — запись останется
без задания, и никто об этом не узнает.

Поэтому очередь всегда строится поверх того же соединения, на котором уже
открыта транзакция сессии. Одна функция, одно место, где это можно сделать
неправильно. Проверяется тестом `tests/test_queue_transaction.py`.
"""

from pgqueuer.db import AsyncpgDriver
from pgqueuer.queries import Queries
from sqlalchemy.ext.asyncio import AsyncSession

# Имена заданий. Собраны здесь, потому что их знают двое — тот, кто ставит
# задание, и воркер: разъехавшиеся строковые литералы ловятся только в проде.
TRANSCRIBE = "transcribe"
REMINDER = "reminder"
INDEX = "index-entry"
# Разметка. Задание ставится на конкретную запись, но обработчик забирает
# всё неразмеченное разом (ADR-0011): при простое это пачка из одной штуки,
# при всплеске — настоящая пачка. Поэтому в нагрузке идентификатор записи
# лежит только ради лога — обработчику он не нужен.
ENRICH = "enrich-entry"
AUDIO_RETENTION = "audio-retention"
HEARTBEAT = "heartbeat"
# Переобобщение тем: раскладка накопленного по темам одной пачкой.
# Это не разметка, а починка того, что разметка по одной записи сделать
# не может в принципе (`core/enrich/regeneralize.py`).
REGENERALIZE = "regeneralize-topics"

# Ретеншен аудио: раз в сутки ночью. Точность здесь не нужна вовсе —
# речь о файлах, которым тридцать дней.
AUDIO_RETENTION_SCHEDULE = "0 4 * * *"

# Переобобщение — раз в сутки ночью, но срабатывает оно **не по расписанию,
# а по накоплению**: сначала считается, сколько записей появилось с прошлого
# прохода, и при малом числе проход не делается вовсе. Расписание здесь только
# повод посмотреть — «раз в N записей» иначе пришлось бы хранить своим
# счётчиком, а он разъехался бы с данными при первом же перепрогоне.
REGENERALIZE_SCHEDULE = "30 4 * * *"

# Касания Фазы 4: утренняя сводка, всплывание, вечерний разбор, ревью.
TOUCH = "touch"

# Тик касаний — раз в пять минут, и это **не** «сводка в 09:00».
#
# Фиксированный `0 9 * * *` не годится по трём причинам сразу, и каждая из них
# ломает его молча (ADR-0013, ось 2):
#
#   1. Europe/Rome летом UTC+2, зимой +1. Час в UTC уедет в конце октября.
#   2. Воркер лежал в 09:00 — сводка пропадёт, и следа об этом не останется.
#      Ровно так пропало напоминание 17 августа.
#   3. Перезапуск воркера в 09:00 может выполнить расписание дважды.
#
# Поэтому расписание здесь — только повод посмотреть, а решение принимается
# по данным: «сейчас у владельца ≥09:00 и сводка за сегодня ещё не уходила».
# Тот же приём, что у переобобщения тем.
#
# Цена названа вслух: 288 пробуждений в сутки, из которых почти все ничего
# не делают. На фоне пульса, который бьёт раз в минуту, это не расход.
TOUCH_SCHEDULE = "*/5 * * * *"

# Пульс воркера — раз в минуту.
#
# Своего сигнала «я жив» у pgqueuer нет: `heartbeat` в таблице расписаний
# обновляется только пока задание расписания выполняется, а по пустой очереди
# отличить «воркер спит без работы» от «воркер лежит» невозможно вовсе.
# Поэтому пульс делается расписанием, которое ничего не делает: библиотека
# при каждом срабатывании обновляет `last_run`, и это единственная запись,
# которую оно порождает — в журнал заданий расписания не пишутся.
#
# Проверять живость нужно ровно потому, что бот и воркер — разные процессы:
# бот бодро отвечает «Принял», когда расшифровывать уже некому. Именно так
# и было 16 августа 2026.
HEARTBEAT_SCHEDULE = "* * * * *"

# Сколько пропущенных ударов считать смертью. Три минуты — это три подряд
# не случившихся срабатывания: одно можно списать на паузу при перезапуске.
HEARTBEAT_STALE_MINUTES = 3


async def queue_on(session: AsyncSession) -> Queries:
    """Очередь поверх соединения сессии — не поверх своего собственного."""
    raw = await (await session.connection()).get_raw_connection()
    return Queries(AsyncpgDriver(raw.driver_connection))
