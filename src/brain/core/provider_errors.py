"""Что означает код ответа провайдера и что из этого следует.

Один модуль на три двери — `core/stt`, `core/llm`, `core/retrieval`. Каждая
из них по-прежнему держит свои классы ошибок и по-прежнему не импортирует
пакет, который её собирает; общим стало только одно: **код ответа доезжает
до места решения объектом, а не строкой внутри сообщения.**

Ради этого модуль и появился. 20 августа 2026 воркер не поднялся из-за `429`:
кончилась бесплатная суточная квота эмбеддингов. Отказ был временный
и проходил сам, но три двери сплющивали `httpx.HTTPStatusError` в текст,
`check_available` заворачивала любой отказ в «модель недоступна», а старт
выходил на `SystemExit`. В итоге из-за кончившейся квоты на **эмбеддинги**
встали расшифровка, напоминания и утренняя сводка — то есть в том числе то,
о чём владелец просил сам.

Отсюда правило: **временный отказ провайдера не останавливает воркер,
настроечный — останавливает.** Второе не смягчается: молчаливый старт
с неверным именем модели — это ровно та поломка, ради ранней встречи
с которой проверка вызовом и заведена (вывод 16 августа 2026).
"""

# Коды, которые проходят сами. `429` — квота или частота, пятисотые — сбой
# на стороне провайдера. Ждать в обоих случаях осмысленно, а останавливаться
# нет: пока мы стоим, не приходят напоминания.
TRANSIENT = frozenset({429, 500, 502, 503, 504})

# Провайдер отвечает этой фразой, когда запрос пришёл из неподдерживаемой
# страны. Код при этом `400`, то есть неотличим от «мы прислали плохой запрос»,
# и без разбора текста совет получался бы неверным. Проверено на живом отказе
# 19 августа 2026 — он положил три задания разметки подряд.
REGION_MARKER = "user location is not supported"


def transient(status: int | None) -> bool:
    """Пройдёт ли этот отказ сам.

    Неизвестный код (сеть отвалилась, ответа не было) считается настроечным.
    Выбор в пользу громкого отказа: молча стартовать при непонятном отказе
    значит вернуть слепоту, из-за которой проверка вызовом появилась.
    """
    return status in TRANSIENT


class ProviderError(RuntimeError):
    """Отказ внешнего провайдера вместе с кодом ответа.

    База для ошибок всех трёх дверей. `status` — то, ради чего она существует:
    без кода нельзя ни отличить квоту от снятой модели, ни дать верный совет.
    `None` означает, что ответа не было вовсе.
    """

    def __init__(self, message: str, *, status: int | None = None) -> None:
        super().__init__(message)
        self.status = status

    @property
    def fatal(self) -> bool:
        """Останавливаться ли из-за этого отказа при старте."""
        return not transient(self.status)


def advice(status: int | None, setting: str, *, message: str = "") -> str:
    """Что владельцу делать с этим отказом.

    Совет зависит от кода намеренно. Старый текст советовал одно и то же —
    «поправьте {setting} в .env», — и для квоты это **неправда**: она считается
    на проект, а не на модель, и смена имени модели её не вернёт. Зато уведёт
    чинить то, что не сломано.
    """
    if status == 429:
        return (
            "Кончилась квота запросов. Она считается на проект целиком, "
            "а не на модель, — менять имя модели незачем.\n"
            "Сбрасывается в полночь по тихоокеанскому времени. "
            "Сколько потрачено сегодня, видно в /status."
        )

    if status is not None and status in TRANSIENT:
        return "Провайдер отвечает ошибкой на своей стороне. Обычно проходит само; повторите позже."

    if status == 400 and REGION_MARKER in message.lower():
        return (
            "Провайдер не обслуживает регион, из которого пришёл запрос. "
            "Дело не в модели и не в ключе — в том, откуда идёт вызов."
        )

    if status in (401, 403):
        return f"Ключ не принят. Проверьте GOOGLE_API_KEY в .env, а не {setting}."

    if status == 404:
        return (
            f"Модели нет или она снята с обслуживания. Поправьте {setting} в .env.\n"
            "Списку моделей верить нельзя: он показывает снятую модель как рабочую."
        )

    return f"Проверьте {setting} и GOOGLE_API_KEY в .env."
