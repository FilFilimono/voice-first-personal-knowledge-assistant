"""Сколько стоит вызов.

Цены живут в коде, а не в базе: их меняет не система, а провайдер, и меняет
редко. Зато они устаревают молча — поэтому рядом с каждой стоит дата проверки,
а незнакомая модель даёт **пустую** стоимость, а не нулевую. Ноль означал бы
«бесплатно», а мы всего лишь не знаем прайс.

Проверено на странице цен 19 августа 2026. Это пункт квартальной проверки:
`gemini-2.5-flash-lite` прожила один день после того, как её записали в ADR.
"""

from decimal import Decimal

MILLION = Decimal(1_000_000)

# модель → (вход, выход) в долларах за 1M токенов
PRICES: dict[str, tuple[Decimal, Decimal]] = {
    "gemini-3.5-flash-lite": (Decimal("0.30"), Decimal("2.50")),
    "gemini-3.1-flash-lite": (Decimal("0.25"), Decimal("1.50")),
    # Чистка расшифровок (ADR-0015, ось 2). Проверено на странице цен
    # 24.08.2026. Внесена сразу вместе с настройкой: незнакомая модель даёт
    # **пустую** стоимость, и расход чистки — треть месячного счёта волны —
    # не был бы виден в `/status` вовсе.
    #
    # Цена **промо, до 31 декабря 2026**: с 1 января 2027 она удваивается
    # (1.50 / 7.50). Записано здесь, а не в голове: иначе счёт вырастет вдвое
    # за ночь, и искать причину будут в системе, где её нет.
    "gemini-3.7-flash": (Decimal("0.75"), Decimal("3.75")),
    # Кандидаты на чистку — те, с которыми `--model` сравнивает `gemini-3.7-flash`
    # (`just eval-cleanup`). Внесены 25.08.2026, после трёх прогонов, каждый
    # из которых закончился строкой «Стоил прогон: $?»: сравнивать модели
    # по деньгам было нечем, хотя ради этого сравнения замер и написан.
    # Проверено на странице цен Google 25.08.2026.
    #
    # У `3.6-flash` цена такая же промо, как у `3.7-flash`: до 31 декабря 2026,
    # с 1 января 2027 — 1.50 / 7.50.
    "gemini-3.6-flash": (Decimal("0.75"), Decimal("3.75")),
    # У `3.5-flash` промо нет — цена постоянная, и она вдвое дороже входа
    # и почти втрое дороже выхода. При том что выход — восемьдесят девять
    # процентов стоимости (см. `cost_usd`), выбор этой модели ради качества
    # надо считать деньгами, а не ощущением.
    "gemini-3.5-flash": (Decimal("1.50"), Decimal("9.00")),
}

# Модели, у которых стоимость вызова посчитать нечем, и это **известно**.
# `batchEmbedContents` не возвращает число токенов вовсе, так что цена
# ($0.15 за 1M входных на 19.08.2026) есть, а помножить её не на что.
#
# Отделено от «незнакомой модели» намеренно: незнакомая — это повод для
# предупреждения в логе, а эта — нет, иначе предупреждение будет писаться
# на каждый запрос индексации и перестанет читаться. Строка в `llm_calls`
# при этом всё равно пишется: она считает **запросы**, а квота провайдера
# считается в запросах, а не в деньгах.
UNPRICED: frozenset[str] = frozenset({"gemini-embedding-001", "gemini-embedding-2"})


def cost_usd(model: str, *, input_tokens: int, output_tokens: int) -> Decimal | None:
    """Стоимость вызова. `None`, если про модель ничего не известно.

    Восемьдесят девять процентов стоимости разметки — это **выход** (замер
    19.08.2026: 2039 входных токенов против 2049 выходных при цене выхода
    в восемь раз выше). Отсюда практическое следствие: разметка дешевеет
    укорачиванием ответа, а не промпта.
    """
    prices = PRICES.get(model)
    if prices is None:
        return None

    for_input, for_output = prices
    return (for_input * input_tokens + for_output * output_tokens) / MILLION
