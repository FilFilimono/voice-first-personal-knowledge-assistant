"""Сколько запросов в сутки даёт бесплатный тир — **на модель**, а не на проект.

Числа провайдера живут в коде рядом с ценами и по тем же правилам, что цены
(`pricing.py`): у каждого написано, **откуда оно взято и когда**, а незнакомая
модель даёт `None`, а не выдуманное число. Ноль в остатке означал бы «кончилось»,
а число из головы в `/status` читалось бы как измеренное — и то и другое хуже
честного «неизвестен».

**Почему на модель.** До 26 августа 2026 в проекте считалось, что суточный лимит
общий: ADR-0014 так и записал совет владельцу — «квота считается на проект».
Провайдер сказал обратное дословно: в теле `429` приходит метрика
`GenerateRequestsPerDayPerProjectPerModel-FreeTier` со значением `20`, то есть
per project **per model**. Это видно и в `llm_calls` за один день: `3.6-flash`
упёрлась на двадцатом запросе, а `3.5-flash-lite` сделала за те же сутки
двадцать два и не отказала ни разу. Одно число «сегодня потрачено 58» не
отвечает на единственный вопрос, ради которого его смотрят, — можно ли сейчас
запустить бэкфилл.

**Почему таблица, а не настройка.** Настройка на каждую модель означала бы, что
смена `CLEANUP_MODEL` тянет за собой ещё одну переменную в `.env`, — а смена
модели задумана как правка `.env`, а не как обряд. Таблица знает лимит по имени
модели: поставили другое имя — либо число нашлось, либо честно «неизвестен».
Число из `.env` при этом **сильнее** таблицы (`daily_limit(override=...)`):
таблица — наблюдение, провайдер меняет лимиты молча, и увидев настоящую границу
владелец обязан уметь поправить её без правки кода. Ровно поэтому ADR-0014
сделал `EMBEDDING_DAILY_QUOTA` настройкой, и она такой и остаётся.

Лимит эмбеддингов сюда намеренно **не переехал**: он живёт в
`EMBEDDING_DAILY_QUOTA` (ADR-0014), и вторая копия того же числа рядом
разъехалась бы с первой молча. Настройки при этом сменили смысл — из «одно
число на все текстовые модели» в «поправка к той модели, которая стоит
в `EMBEDDING_MODEL` и `ENRICH_MODEL`»; связывает их с именами моделей
`configured()`.
"""

from brain.config import Settings

# модель → сколько успешных запросов в сутки даёт бесплатный тир
#
# `3.6-flash` и `3.5-flash`: 20. Наблюдено 26.08.2026 — не из документации,
# а из тела ответа провайдера на `429`:
#   "quotaMetric": "generativelanguage.googleapis.com/generate_content_free_tier_requests"
#   "quotaId": "GenerateRequestsPerDayPerProjectPerModel-FreeTier"
#   "quotaValue": "20"
# В тот день чистка (`3.6-flash`) встала после девятнадцати успешных вызовов,
# а сравнение моделей на том же архиве не доехало до конца по той же причине.
#
# `3.5-flash-lite` здесь нет намеренно: её лимит **больше двадцати** (26.08.2026
# она сделала 22 запроса без единого отказа, а 25.08 — за девяносто), но
# настоящей границы никто не видел. Записать сюда «90» значило бы выдать
# наблюдение снизу за измеренный потолок.
FREE_TIER_DAILY_REQUESTS: dict[str, int] = {
    "gemini-3.6-flash": 20,
    "gemini-3.5-flash": 20,
}


def daily_limit(model: str, *, override: int | None = None) -> int | None:
    """Суточный лимит запросов к модели. `None` — **неизвестен**, а не «нет».

    `override` — число из `.env`. Оно сильнее таблицы: таблица устаревает молча,
    а владелец, упёршийся в настоящую границу, должен уметь сказать её системе,
    не трогая код.
    """
    if override is not None:
        return override
    return FREE_TIER_DAILY_REQUESTS.get(model)


def configured(settings: Settings) -> dict[str, int]:
    """Поправки владельца из `.env`: модель → её суточный лимит.

    Настройка привязана не к тиру и не к назначению, а к **имени модели**,
    которое в ней стоит: лимит провайдер считает на модель, и одна и та же
    модель в `ENRICH_MODEL` и `CLEANUP_MODEL` тратит один и тот же лимит.
    """
    pairs = (
        (settings.embedding_model, settings.embedding_daily_quota),
        (settings.enrich_model, settings.enrich_daily_quota),
    )
    return {model: limit for model, limit in pairs if limit is not None}
