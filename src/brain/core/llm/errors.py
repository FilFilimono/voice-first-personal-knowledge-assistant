"""Отказы модели. Разные сорта разводятся намеренно.

Очередь обходится с ними по-разному: временный отказ повторяется с задержкой,
окончательный повторять бессмысленно — результат будет тот же, а приватная
запись при пяти попытках постучалась бы наружу пять раз.
"""


class LlmError(RuntimeError):
    """Модель не ответила или ответила не тем. Повторять имеет смысл."""


class PrivateContentError(LlmError):
    """Приватная запись дошла до двери наружу. Инвариант 5.

    Повторять бессмысленно: приватность не меняется от того, что мы попробуем
    ещё раз. Ошибка означает не сбой провайдера, а ошибку в коде выше.
    """


class ProviderUnavailableError(LlmError):
    """Модели нет или она снята с обслуживания. Проверяется при старте воркера."""


class TierNotAvailableError(LlmError):
    """Обращение к тиру, которого в этой фазе нет.

    Дорогой тир появляется в Фазе 6 (ADR-0004). До неё обращение к нему обязано
    падать явно и **не деградировать молча в дешёвую модель**: тихая подмена
    тира — это ровно тот баг, который потом ищут неделю.
    """
